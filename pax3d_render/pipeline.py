    def _terrain_shader_for(self, config):
        """The TERRAIN_SPLAT variant matching this config's optional
        features (compiled lazily per combo, invalidated by
        _recompile_pbr — the glass discipline)."""
        key = (config['normal_array'] is not None,
               config['orm_array'] is not None,
               config['macro_map'] is not None,
               config['hex_tiling'],
               config['height_blend'],
               config['water'] is not None)
        shader = self._terrain_shaders.get(key)
        if shader is None:
            defines = self._get_pbr_defines()
            defines['TERRAIN_SPLAT'] = True
            if key[0]:
                defines['TERRAIN_SPLAT_NORMALS'] = True
            if key[1]:
                defines['TERRAIN_SPLAT_ORM'] = True
            if key[2]:
                defines['TERRAIN_SPLAT_MACRO'] = True
            if key[3]:
                defines['TERRAIN_HEX_TILING'] = True
            if key[4]:
                defines['TERRAIN_HEIGHT_BLEND'] = True
            if key[5]:
                defines['TERRAIN_WATER'] = True
            shader = shaderutils.make_shader(
                'pax_pbr_terrain', 'pax_pbr.vert', 'pax_pbr.frag', defines)
            self._terrain_shaders[key] = shader
        return shader

    def _apply_terrain_splat(self, nodepath, config):
        """Compose the terrain variant + its inputs onto the node (same
        attrib discipline as _apply_glass_shader: existing shader state
        survives; no override, so the shadow camera's initial-state
        attrib still wins the depth pass — terrain casts/receives
        exactly as before)."""
        prev = nodepath.get_attrib(p3d.ShaderAttrib)
        if prev is None:
            prev = p3d.ShaderAttrib.make()
        nodepath.set_attrib(prev.set_shader(
            self._terrain_shader_for(config)))
        nodepath.set_shader_input('terrain_albedo', config['albedo_array'])
        nodepath.set_shader_input('terrain_splat', config['splat_map'])
        nodepath.set_shader_input(
            'u_terrain_uv_scales', p3d.LVecBase4(*config['uv_scales']))
        nodepath.set_shader_input(
            'u_terrain_splat_transform',
            p3d.LVecBase4(*config['splat_transform']))
        if config['normal_array'] is not None:
            nodepath.set_shader_input('terrain_normal',
                                      config['normal_array'])
            nodepath.set_shader_input(
                'u_terrain_normal_fade',
                p3d.LVecBase2(*config['normal_fade']))
        if config['orm_array'] is not None:
            nodepath.set_shader_input('terrain_orm', config['orm_array'])
        if config['macro_map'] is not None:
            nodepath.set_shader_input('terrain_macro', config['macro_map'])
            nodepath.set_shader_input('u_terrain_macro_scale',
                                      float(config['macro_uv_scale']))
            nodepath.set_shader_input('u_terrain_macro_strength',
                                      float(config['macro_strength']))
        if config['hex_tiling']:
            nodepath.set_shader_input(
                'u_terrain_hex',
                p3d.LVecBase2(config['hex_cell_size'],
                              config['hex_contrast']))
            nodepath.set_shader_input(
                'u_terrain_hex_rot',
                p3d.LVecBase4(*config['hex_rotation']))
            nodepath.set_shader_input(
                'u_terrain_hex_off',
                p3d.LVecBase2(*config['hex_offset']))
        if config['height_blend']:
            nodepath.set_shader_input(
                'u_terrain_height_sharp',
                float(config['height_sharpness']))
        water = config['water']
        if water is not None:
            nodepath.set_shader_input(
                'u_terrain_water',
                p3d.LVecBase4(water['water_z'], water['band_m'],
                              water['dark'], water['rough_mult']))
            phase = (water['anim_phase']
                     if water['anim_phase'] is not None else 0.0)
            nodepath.set_shader_input(
                'u_terrain_water2',
                p3d.LVecBase4(water['sat'], water['anim_amp'],
                              1.0 / water['anim_scale'], phase))

    def _reapply_terrain_splat(self):
        """Re-push (freshly invalidated) terrain variants onto every
        registered terrain node after a pipeline shader recompile."""
        self._terrain_nodes = [e for e in self._terrain_nodes
                               if not e[0].is_empty()]
        for nodepath, config in self._terrain_nodes:
            self._apply_terrain_splat(nodepath, config)

    def set_terrain_splat(self, nodepath, albedo_array, splat_map,
                          normal_array=None, orm_array=None,
                          uv_scales=(1.0, 1.0, 1.0, 1.0),
                          splat_transform=(0.0, 0.0, 1.0, 1.0),
                          macro_map=None, macro_uv_scale=1.0,
                          macro_strength=0.15,
                          normal_fade=(200.0, 400.0),
                          hex_tiling=False, hex_cell_size=4.0,
                          hex_rotation=1.0, hex_contrast=6.0,
                          hex_offset=(0.0, 0.0),
                          height_blend=False, height_sharpness=8.0):
        """Give `nodepath` (a terrain chunk subtree) a splat-blended
        layer material (ER-001): up to 4 PBR layers weighted per-
        fragment by an RGBA splat map, composing with sun/shadows/fog/
        aerial-perspective/IBL exactly like every other PBR material
        (it is the same shader — only the material inputs change).

        Args:
            albedo_array: 2D texture ARRAY (setup_2d_texture_array /
                intake-built), one slice per layer, uniform size. Slice
                i is weighted by splat channel i (R,G,B,A). Color
                texture — sRGB/compression-eligible, NOT under the
                ER-003 data contract.
            splat_map: RGBA weight texture covering the chunk. Weights
                are renormalized in-shader (an all-zero texel falls
                back to layer 0). DATA texture: pass it through
                data_texture() (the game-side ER-003 commitment) so it
                is never compressed — DXT on weights smears blends.
            normal_array: optional tangent-space normal array (+Y/
                OpenGL convention, slices aligned with albedo). Chunk
                meshes need NO tangent column: the TBN is analytic from
                the world-planar UV convention (u->+world_x,
                v->+world_y; Gram-Schmidt on steep faces). If your
                planar mapping flips v, flip the green channel at
                intake.
            orm_array: optional occlusion(r)/roughness(g)/metallic(b)
                array. Without it the layers use the node MATERIAL's
                roughness/metallic (the dispatcher's per-planet
                values). With it, material values MULTIPLY the map
                (glTF semantic).
            uv_scales: per-layer detail tiling scale applied to the
                mesh UV (chunks carry world-aligned planar UVs).
            splat_transform: (off_u, off_v, scale_u, scale_v) mapping
                base UV -> splat UV; default identity for chunk-local
                0..1 UVs. World-aligned continuous UVs use this to
                window the per-chunk splat map.
            macro_map: optional single-channel low-frequency variation
                texture; modulates albedo brightness by
                mix(1, 2*macro, strength) — a 0.5 texel is an exact
                no-op. Sample at 100-500 m periods via macro_uv_scale.
            normal_fade: (start, end) view distance over which detail
                normals fade flat (sparkle/moire control; terrain
                fills most of the frame).
            hex_tiling: enable stochastic hex-tiling of the DETAIL
                sampling (ER-007): every fragment blends the 3 nearest
                hex cells' samples, each cell with a hashed phase
                offset + rotation — the verbatim motif repetition of
                wrap-repeat tiling ("sand ripples marching in rows")
                breaks up. Costs 3x the array taps (normals ride the
                same cells; the normal_fade still flattens them at
                range). Off = byte-identical to the pre-ER-007 path.
            hex_cell_size: hex cell size in DETAIL-UV repeats (~how
                many texture repeats each cell shows verbatim).
                Smaller de-repeats harder but spends more area in
                blend seams.
            hex_rotation: per-cell random rotation range as a fraction
                of +-180 deg — scalar or per-layer 4-sequence.
                Rotation is what kills directional motifs (dune
                ripples); set a layer to 0.0 to keep a strongly
                anisotropic set axis-aligned (offsets still apply).
            hex_contrast: weight-sharpening exponent (the cheap
                variance-preserving stand-in for histogram-preserving
                blending). Higher = narrower blend seams, more of each
                cell shown pure; 1.0 = plain barycentric (washed-out
                seams).
            hex_offset: per-chunk detail-UV offset in BASE-UV units,
                added before the per-layer uv_scales in the HEX path
                only (ER-007 adoption follow-up: the chunk-border motif
                seam). Chunk-local base UVs restart every chunk, so the
                hex cell HASH reseeds along borders (whole-repeat
                uv_scales keep the texture PHASE continuous — the hash
                input is what jumps). Pass each chunk's world offset in
                base-UV units and cell ids become world-anchored: the
                motif is seamless across chunk borders. Default (0,0)
                is an exact no-op.
            height_blend: enable height-blend sharpening (the ER-007
                rider, unblocked by the height8-in-albedo.a intake
                contract 2026-07-21): splat weights are resharpened per
                fragment by w_i * 2^(height_sharpness * albedo_i.a),
                renormalized, so at a blend boundary the texel whose
                material stands TALLER wins — transitions follow the
                height texture (grass interlocks with dirt) instead of
                a smooth crossfade. The sharpened weights drive albedo,
                ORM AND detail normals (material coherence). CONTRACT:
                equal heights cancel exactly (common factor), so an
                all-flat palette (Deep Desert: every slice flat-128) is
                a visual no-op — plain splat weights; a flat-128 slice
                inside a height-rich palette (beach-sand) competes at
                its constant 0.5. Costs 4 extra albedo array taps on
                the plain path; on the hex path the up-front taps ARE
                the blend taps (no extra samples).
            height_sharpness: the softmax exponent k. 0 = exact no-op
                (kwarg live but inert); useful range ~4-16: at k=8 a
                0.25 height advantage outweighs a 4x splat-weight
                deficit (2^2 = 4). Raise it if transitions still read
                as crossfades, lower it if blend borders turn to hard
                jigsaw edges.

        Layer-weight computation lives in ONE shader function
        (terrain_layer_weights) — the ratified v2 seam. Hex-tiling
        landed there as TERRAIN_HEX_TILING (ER-007) and height-blend
        sharpening as TERRAIN_HEIGHT_BLEND (the ER-007 rider) — both
        exactly at the seam, nothing else restructured. Re-calling with
        new arguments reconfigures in place; clear_terrain_splat()
        restores the node byte-identically (paxtest
        test_terrain_splat).
        """
        try:
            hex_rot = tuple(float(r) for r in hex_rotation)
        except TypeError:
            hex_rot = (float(hex_rotation),) * 4
        if len(hex_rot) != 4:
            raise ValueError('hex_rotation must be a scalar or a '
                             '4-sequence (one value per layer)')
        hex_off = tuple(float(o) for o in hex_offset)
        if len(hex_off) != 2:
            raise ValueError('hex_offset must be a 2-sequence '
                             '(base-UV units)')
        config = {
            'albedo_array': albedo_array,
            'splat_map': splat_map,
            'normal_array': normal_array,
            'orm_array': orm_array,
            'uv_scales': tuple(float(s) for s in uv_scales),
            'splat_transform': tuple(float(s) for s in splat_transform),
            'macro_map': macro_map,
            'macro_uv_scale': float(macro_uv_scale),
            'macro_strength': float(macro_strength),
            'normal_fade': tuple(float(f) for f in normal_fade),
            'hex_tiling': bool(hex_tiling),
            'hex_cell_size': float(hex_cell_size),
            'hex_rotation': hex_rot,
            'hex_contrast': float(hex_contrast),
            'hex_offset': hex_off,
            'height_blend': bool(height_blend),
            'height_sharpness': float(height_sharpness),
            'water': None,
        }
        idx = next((i for i, e in enumerate(self._terrain_nodes)
                    if e[0] == nodepath), None)
        if idx is None:
            self._terrain_nodes.append((nodepath, config))
        else:
            # Re-dressing a chunk keeps its water contract (ER-010) —
            # like the other per-node contracts, it lives until
            # explicitly cleared (paxtest test_terrain_water).
            config['water'] = self._terrain_nodes[idx][1].get('water')
            self._terrain_nodes[idx] = (nodepath, config)
        self._apply_terrain_splat(nodepath, config)

    def clear_terrain_splat(self, nodepath):
        """Undo set_terrain_splat(): the node reverts to the inherited
        pipeline shader and its prior material path, byte-identical to
        untouched (paxtest test_terrain_splat opt-out check)."""
        idx = next((i for i, e in enumerate(self._terrain_nodes)
                    if e[0] == nodepath), None)
        if idx is None:
            return
        self._terrain_nodes.pop(idx)
        nodepath.clear_shader()
        for name in ('terrain_albedo', 'terrain_splat', 'terrain_normal',
                     'terrain_orm', 'terrain_macro',
                     'u_terrain_uv_scales', 'u_terrain_splat_transform',
                     'u_terrain_normal_fade', 'u_terrain_macro_scale',
                     'u_terrain_macro_strength', 'u_terrain_hex',
                     'u_terrain_hex_rot', 'u_terrain_hex_off',
                     'u_terrain_height_sharp', 'u_terrain_water',
                     'u_terrain_water2'):
            nodepath.clear_shader_input(name)
        self._refresh_terrain_water_anim()

    def set_terrain_water(self, nodepath, water_z, band_m=1.0, dark=0.55,
                          rough_mult=0.35, sat=1.25, anim_amp=0.0,
                          anim_period=12.0, anim_scale=6.0,
                          anim_phase=None):
        """Give a set_terrain_splat() node a wet-sand waterline (ER-010):
        fragments below `water_z` + band render WET — darker, more
        saturated albedo and much lower roughness (the retreating-wave
        sheen is a specular read). Wetness is by WORLD Z only, applied
        to ALL splat layers alike (wet rock and wet soil darken too —
        no layer-semantics coupling), and it applies BELOW the waterline
        as much as above: the seafloor visible through the game's
        depth-alpha shallows reads wet, not bone-dry.

        wet = 1 below water_z, easing to 0 across [water_z,
        water_z + band_m]. Every change is applied via mix(dry, wet, w),
        so wet == 0 fragments compute exactly the water-off arithmetic;
        nodes that never call this keep the water-free shader variant —
        byte-identical to today by construction.

        Args:
            water_z: sea level in WORLD z (the game's world.water
                contract). None clears the contract (same as
                clear_terrain_water()).
            band_m: wet reach above sea level in world units — the
                dark mirror band the last wave left.
            dark: wet albedo multiplier (0.55 reads like soaked sand).
            rough_mult: wet roughness multiplier — the sheen lever;
                the wet result is clamped to [0, 1].
            sat: wet chroma expansion about Rec.709 luminance (1.0 =
                none). Applied with `dark` in one transform; the two
                commute exactly.
            anim_amp: breathing-edge amplitude in world z units (the
                ER-010 stretch goal). 0 (default) = the static band,
                EXACT (the edge offset is amp * noise; x + 0.0*n == x).
                ~0.3-0.6 sells the advancing/retreating wash.
            anim_period: breathe cycle in seconds (~8-15 reads like
                shore wash).
            anim_scale: along-shore spatial variation cell size in
                world units — each ~cell breathes with its own phase
                (static value noise of world xy phase-shifts the
                shared cycle).
            anim_phase: None (default) = the pipeline's per-frame task
                drives the phase from the global clock. A float pins
                the phase in radians (determinism valve — paxtest and
                screenshot A/Bs).

        Re-calling reconfigures in place; set_terrain_splat() re-calls
        on the same node PRESERVE the water contract (chunk re-dressing
        must not silently dry the shore). Gated by paxtest
        test_terrain_water.
        """
        if water_z is None:
            self.clear_terrain_water(nodepath)
            return
        idx = next((i for i, e in enumerate(self._terrain_nodes)
                    if e[0] == nodepath), None)
        if idx is None:
            raise ValueError('set_terrain_water: node has no terrain '
                             'splat config — call set_terrain_splat() '
                             'first')
        water = {
            'water_z': float(water_z),
            'band_m': max(float(band_m), 1e-4),
            'dark': float(dark),
            'rough_mult': float(rough_mult),
            'sat': float(sat),
            'anim_amp': float(anim_amp),
            'anim_period': max(float(anim_period), 1e-3),
            'anim_scale': max(float(anim_scale), 1e-3),
            'anim_phase': (None if anim_phase is None
                           else float(anim_phase)),
        }
        nodepath, config = self._terrain_nodes[idx]
        config['water'] = water
        self._apply_terrain_splat(nodepath, config)
        self._refresh_terrain_water_anim()

    def clear_terrain_water(self, nodepath):
        """Undo set_terrain_water(): the node reverts to the water-free
        terrain variant, byte-identical to never having called it
        (paxtest test_terrain_water opt-out check). The splat config
        itself stays."""
        idx = next((i for i, e in enumerate(self._terrain_nodes)
                    if e[0] == nodepath), None)
        if idx is None:
            return
        nodepath, config = self._terrain_nodes[idx]
        if config.get('water') is None:
            return
        config['water'] = None
        self._apply_terrain_splat(nodepath, config)
        for name in ('u_terrain_water', 'u_terrain_water2'):
            nodepath.clear_shader_input(name)
        self._refresh_terrain_water_anim()

    def _refresh_terrain_water_anim(self):
        """Rebuild the per-frame water-anim worklist: entries with a
        live breathing edge only (amp > 0, phase clock-driven)."""
        self._terrain_water_anim = [
            (np_, cfg['water']) for np_, cfg in self._terrain_nodes
            if cfg.get('water') is not None
            and cfg['water']['anim_amp'] > 0.0
            and cfg['water']['anim_phase'] is None]

