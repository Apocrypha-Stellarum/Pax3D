    _MORPH_LIVE_SLOTS = 16   # live-slider slots (character-lane contract:
                             # 52 addressable, <=16 driven; ARKit viseme
                             # ceiling). Overflow keeps the largest |w|.
    _MORPH_EPS = 1e-4        # slider magnitude below this is "at rest"
    _MORPH_FAST_BAKE = True  # zero-copy bake when the loader's morph
                             # array already matches the texture layout
                             # (Session AB). The gate byte-compares the
                             # fast and reorder paths; False forces the
                             # reorder path (test hook, not a user knob).
    _MORPH_NUMPY_REORDER = True  # reorder path uses numpy's column
                             # gather when importable (it ships with
                             # panda3d-gltf, so it is present wherever
                             # glTF morphs are; kade's pack orders
                             # columns non-canonically on 5/6 prims —
                             # measured 0.34 s/face pure-Python vs
                             # ~0.1 s with the gather). Pure-Python
                             # fallback stays; all three bake variants
                             # are byte-compared in-gate.

    def _get_gpu_morph_shader(self):
        """The GPU_MORPHS PBR variant for the CURRENT pipeline defines
        (invalidated by _recompile_pbr, the glass discipline)."""
        if self._gpu_morph_shader is None:
            defines = self._get_pbr_defines()
            defines['GPU_MORPHS'] = True
            defines['MORPH_LIVE'] = self._MORPH_LIVE_SLOTS
            self._gpu_morph_shader = shaderutils.make_shader(
                'pax_pbr_gpu_morphs', 'pax_pbr.vert', 'pax_pbr.frag',
                defines)
        return self._gpu_morph_shader

    @staticmethod
    def _locate_morph_col(vdata, name):
        """(array index, byte start, byte stride) of one float32x3
        morph column, or None if the column is absent."""
        iname = p3d.InternalName.make(name)
        fmt = vdata.get_format()
        ai = fmt.get_array_with(iname)
        if ai < 0:
            return None
        arrf = fmt.get_array(ai)
        col = arrf.get_column(iname)
        if (col.get_numeric_type() != p3d.Geom.NT_float32
                or col.get_num_components() != 3):
            raise ValueError(
                f'morph column {name} is not float32x3 '
                f'(type {col.get_numeric_type()}, '
                f'{col.get_num_components()} comps)')
        return ai, col.get_start(), arrf.get_stride()

    @classmethod
    def _bake_morph_texture(cls, vdata, slider_names):
        """RGB32F delta texture for one vdata, VERTEX-MAJOR (Session
        AB): width = 2 * len(slider_names) texels — position delta at
        x = 2t, normal delta at x = 2t + 1, t keyed by the CHARACTER-
        level slider order so every vdata under one character agrees
        on target indices — height = vertex rows.

        Vertex-major is not a style choice: it is byte-for-byte the
        layout the loader already stores morph columns in (ONE
        interleaved array, [vertex.morph.s, normal.morph.s, ...]
        tightly packed per vertex — measured on production heads,
        Session AB). When a vdata's column order matches the slider
        order (wren: head/torso/lash prims, ~95% of rows) the bake is
        a ZERO-COPY upload of the array's raw bytes; vdatas whose
        column order differs (wren's eye prims) or that carry a
        subset take a per-column reorder pass, and missing columns
        stay zero texels (a slider that does not touch this vdata is
        a no-op there, same as the CPU path). The two paths are
        byte-compared in-gate.

        Ram row 0 = texcoord v=0 and set_ram_image_as('RGB') keeps
        float component order — both MEASURED (TexturePeeker probe,
        Session Z) and re-proven end-to-end by the gate's GPU-vs-CPU
        image check. data_texture() pins the ER-003 contract; nearest
        filtering + texel-center UVs make every fetch exact. Returns
        (texture, texel_size) or None if the vdata carries no morph
        columns for any of the names."""
        n = vdata.get_num_rows()
        ncols = 2 * len(slider_names)
        rowbytes = 12 * ncols
        fmt = vdata.get_format()

        image = None
        if cls._MORPH_FAST_BAKE:
            want = []
            for name in slider_names:
                want.append('vertex.morph.' + name)
                want.append('normal.morph.' + name)
            for ai in range(fmt.get_num_arrays()):
                arrf = fmt.get_array(ai)
                if (arrf.get_num_columns() != ncols
                        or arrf.get_stride() != rowbytes):
                    continue
                if all(str(arrf.get_column(ci).get_name()) == want[ci]
                       and arrf.get_column(ci).get_start() == 12 * ci
                       and (arrf.get_column(ci).get_numeric_type()
                            == p3d.Geom.NT_float32)
                       and arrf.get_column(ci).get_num_components() == 3
                       for ci in range(ncols)):
                    image = vdata.get_array(ai).get_handle().get_data()
                    break
        if image is None:
            cols = []   # (dest column, src array, byte start, stride)
            for t, name in enumerate(slider_names):
                for k, prefix in enumerate(('vertex.morph.',
                                            'normal.morph.')):
                    loc = cls._locate_morph_col(vdata, prefix + name)
                    if loc is not None:
                        cols.append((2 * t + k,) + loc)
            if not cols:
                return None
            raws = {ai: bytes(vdata.get_array(ai).get_handle()
                              .get_data())
                    for ai in {c[1] for c in cols}}
            numpy = None
            if cls._MORPH_NUMPY_REORDER:
                try:
                    import numpy
                except ImportError:
                    numpy = None
            if numpy is not None:
                views = {
                    ai: numpy.frombuffer(raw, numpy.uint8).reshape(
                        n, fmt.get_array(ai).get_stride())
                    for ai, raw in raws.items()}
                arr = numpy.zeros((n, rowbytes), numpy.uint8)
                for c, ai, start, _stride in cols:
                    arr[:, 12 * c:12 * c + 12] = (
                        views[ai][:, start:start + 12])
                image = arr.tobytes()
            else:
                out = bytearray(rowbytes * n)
                for c, ai, start, stride in cols:
                    raw = raws[ai]
                    o = start
                    d = 12 * c
                    for _r in range(n):
                        out[d:d + 12] = raw[o:o + 12]
                        o += stride
                        d += rowbytes
                image = bytes(out)
        tex = p3d.Texture('pax3d_morph_deltas')
        tex.setup_2d_texture(ncols, n, p3d.Texture.T_float,
                             p3d.Texture.F_rgb32)
        tex.set_minfilter(p3d.SamplerState.FT_nearest)
        tex.set_magfilter(p3d.SamplerState.FT_nearest)
        tex.set_wrap_u(p3d.SamplerState.WM_clamp)
        tex.set_wrap_v(p3d.SamplerState.WM_clamp)
        tex.set_ram_image_as(image, 'RGB')
        data_texture(tex)
        return tex, p3d.LVecBase2(1.0 / ncols, 1.0 / n)

    @staticmethod
    def _character_sliders(model_np):
        """[(row, name, CharacterSlider)] for the first Character under
        model_np that carries sliders, in bundle tree order (stable —
        fixed by the file, unlike get_anim_names(), fact #12)."""
        for char_np in model_np.find_all_matches('**/+Character'):
            bundle = char_np.node().get_bundle(0)
            out = []

            def walk(group):
                for i in range(group.get_num_children()):
                    child = group.get_child(i)
                    if isinstance(child, p3d.CharacterSlider):
                        out.append(child)
                    walk(child)

            walk(bundle)
            if out:
                return [(row, s.get_name(), s)
                        for row, s in enumerate(out)]
        return []

    def set_gpu_morphs(self, model_np, enabled=True):
        """Render this character's morph sliders on the GPU while
        hardware skinning stays ON — the fix for fact #15 (the HW
        skinning path silently drops sliders; the CPU valve renders
        them but costs ~2 ms per production head and cannot scale to
        crowds). Returns the number of morph geoms converted (0 = the
        model has no morph columns).

        Mechanism: every Geom whose vertex data carries a slider table
        gets (1) a per-vdata RGB32F delta texture (position + normal
        deltas per target, ER-003 data-texture contract), (2) a plain
        float32 'morph_index' vertex column carrying the row id — one
        addressing mechanism everywhere (chosen when the GLSL-120 path
        still existed; no gl_VertexID dependence, works on stock 1.10
        unchanged) — and (3) a GPU_MORPHS compile of the PBR shader
        composed onto its geom state (the alpha-mask seam: root-level
        inputs and flags still compose through). Slider values are
        read from the Character each frame and pushed as a compact
        <=16-slot (row, weight) uniform array per model — O(live
        sliders), the writes-are-sparse contract from the character
        lane. All 52 ARKit targets stay addressable; overflow beyond
        16 live keeps the largest |weight| and warns once.

        Requires the hardware-skinning path to be ACTIVE on the node
        (the pipeline default): with CPU skinning the vdata is already
        morph-animated on the CPU and the shader would apply deltas
        twice. Do not combine with set_hardware_skinning(np, False).

        `enabled=False` restores the saved geom states byte-identically
        (the added inert vertex column stays — no shader reads it
        without the GPU_MORPHS attribute binding).

        Crowds (Session AB): a `copy_to` clone of an ENABLED template
        arrives with the variant states and the SHARED delta textures
        already on its geoms (states and textures are pointer-shared
        by the copy; the vdata is deep-copied by the Character, but it
        is already converted) — yet it renders the TEMPLATE's face,
        because it inherits the template's slider uniform block.
        Call set_gpu_morphs(clone) to give it its OWN face: the call
        detects the variant states, skips the bake entirely (no new
        textures, milliseconds), and registers the clone's own
        CharacterSliders + uniform block. Disable on a clone stops
        driving it (its geoms keep the as-copied variant states, its
        sliders read as zero) and leaves the template untouched.

        Known limits (documented, field-evidence-gated like the
        alpha-mask depth caveat): the shadow depth pass renders the
        UNMORPHED silhouette; tangents keep base values (the loader
        ships no tangent deltas — measured); a geom carries ONE PBR
        variant, so glass/alpha-mask/terrain and GPU morphs do not
        stack on the same geom."""
        idx = next((i for i, e in enumerate(self._gpu_morph_entries)
                    if e['np'] == model_np), None)
        if not enabled:
            if idx is None:
                return 0
            entry = self._gpu_morph_entries.pop(idx)
            for gnode, geom_i, orig_state, _tex, _texel in entry['geoms']:
                gnode.set_geom_state(geom_i, orig_state)
            if entry.get('reused'):
                # A clone's "original" geom states arrived already
                # converted with the copy, so restoring them keeps the
                # GPU_MORPHS shader active — clearing the input would
                # assert at draw ("u_morphs is not present"). Park a
                # zeroed block instead: the clone renders at rest.
                pta = entry['pta']
                for i in range(self._MORPH_LIVE_SLOTS):
                    pta.set_element(i, p3d.LVecBase2f(0.0, 0.0))
                model_np.set_shader_input('u_morphs', pta)
            else:
                model_np.clear_shader_input('u_morphs')
            return len(entry['geoms'])
        if idx is not None:
            return len(self._gpu_morph_entries[idx]['geoms'])

        sliders = self._character_sliders(model_np)
        if not sliders:
            return 0
        names = [name for _row, name, _s in sliders]

        geoms = []
        # source vdata C++ pointer -> (source wrapper, new vdata, tex,
        # texel). Keyed by .this, NOT id(): the Python wrapper is not
        # stable across get_vertex_data() calls, so id() never hits for
        # shared vdatas and a collected wrapper's id can be REUSED by a
        # different vdata (false hit -> wrong texture). The source
        # wrapper in the value keeps the pointer alive for the call.
        baked = {}
        any_reused = False
        iname_tex = p3d.InternalName.make('u_morph_tex')
        gnode_paths = list(model_np.find_all_matches('**/+GeomNode'))
        if isinstance(model_np.node(), p3d.GeomNode):
            gnode_paths.insert(0, model_np)
        for np_ in gnode_paths:
            gnode = np_.node()
            for i in range(gnode.get_num_geoms()):
                vdata = gnode.get_geom(i).get_vertex_data()
                if vdata.get_slider_table() is None:
                    continue
                orig_state = gnode.get_geom_state(i)
                # A copy_to clone of a converted template: the variant
                # state + shared delta texture came with the copy —
                # reuse them, zero re-bake (Session AB crowd contract).
                sa = orig_state.get_attrib(p3d.ShaderAttrib)
                if sa is not None:
                    reuse = sa.get_shader_input(iname_tex).get_texture()
                    if reuse is not None:
                        texel = p3d.LVecBase2(
                            1.0 / reuse.get_x_size(),
                            1.0 / reuse.get_y_size())
                        geoms.append((gnode, i, orig_state, reuse,
                                      texel))
                        any_reused = True
                        continue
                cached = baked.get(vdata.this)
                if cached is None:
                    result = self._bake_morph_texture(vdata, names)
                    if result is None:
                        continue
                    tex, texel = result
                    new_vdata = self._add_morph_index_column(
                        gnode, i, vdata)
                    baked[vdata.this] = (vdata, new_vdata, tex, texel)
                else:
                    _src, new_vdata, tex, texel = cached
                    gnode.modify_geom(i).set_vertex_data(new_vdata)
                geoms.append((gnode, i, orig_state, tex, texel))
        if not geoms:
            return 0

        pta = p3d.PTA_LVecBase2f.empty_array(self._MORPH_LIVE_SLOTS)
        for i in range(self._MORPH_LIVE_SLOTS):
            pta.set_element(i, p3d.LVecBase2f(0.0, 0.0))
        model_np.set_shader_input('u_morphs', pta)

        entry = {'np': model_np, 'geoms': geoms, 'sliders': sliders,
                 'pta': pta, 'last': None, 'warned': False,
                 'reused': any_reused}
        self._gpu_morph_entries.append(entry)
        for gnode, geom_i, orig_state, tex, texel in geoms:
            self._apply_gpu_morph_state(gnode, geom_i, orig_state,
                                        tex, texel)
        return len(geoms)

    @staticmethod
    def _add_morph_index_column(gnode, geom_i, vdata):
        """Append a float32 'morph_index' column (its own array) filled
        with each vertex's row id, in place on this geom's vdata. No-op
        if the column is already present (a re-enable after disable, or
        a shared-vdata sibling geom). Returns the (possibly new) vdata
        for cache sharing."""
        iname = p3d.InternalName.make('morph_index')
        if vdata.get_format().get_array_with(iname) >= 0:
            return vdata
        new_vdata = gnode.modify_geom(geom_i).modify_vertex_data()
        fmt = p3d.GeomVertexFormat(new_vdata.get_format())
        arr = p3d.GeomVertexArrayFormat()
        arr.add_column(iname, 1, p3d.Geom.NT_float32, p3d.Geom.C_other)
        fmt.add_array(arr)
        new_vdata.set_format(p3d.GeomVertexFormat.register_format(fmt))
        # bulk fill: array('f') is C-speed and 4-byte on every platform
        # we ship (asserted); the row id sequence IS the byte image.
        import array as stdarray
        buf = stdarray.array('f', range(new_vdata.get_num_rows()))
        assert buf.itemsize == 4
        ai = new_vdata.get_format().get_array_with(iname)
        new_vdata.modify_array(ai).modify_handle().set_data(
            buf.tobytes())
        return new_vdata

    def _apply_gpu_morph_state(self, gnode, geom_i, orig_state, tex,
                               texel):
        """Compose the GPU_MORPHS variant + per-geom inputs onto ONE
        geom's original state (the alpha-mask pattern)."""
        prev = orig_state.get_attrib(p3d.ShaderAttrib)
        sattr = prev if prev is not None else p3d.ShaderAttrib.make()
        sattr = sattr.set_shader(self._get_gpu_morph_shader())
        sattr = sattr.set_shader_input(p3d.ShaderInput('u_morph_tex', tex))
        sattr = sattr.set_shader_input(
            p3d.ShaderInput('u_morph_texel', texel))
        gnode.set_geom_state(geom_i, orig_state.set_attrib(sattr))

    def _reapply_gpu_morphs(self):
        """Re-push the (freshly invalidated) morph variants onto every
        registered geom after a pipeline shader recompile."""
        self._gpu_morph_entries = [e for e in self._gpu_morph_entries
                                   if not e['np'].is_empty()]
        for entry in self._gpu_morph_entries:
            for gnode, geom_i, orig_state, tex, texel in entry['geoms']:
                self._apply_gpu_morph_state(gnode, geom_i, orig_state,
                                            tex, texel)

    def _step_gpu_morphs(self):
        """Per-frame slider push: read each registered character's
        slider values, refill its compact (row, weight) uniform array
        only when the live set changed. O(sliders) per character —
        the PTA is uploaded by reference, no set_shader_input churn."""
        self._gpu_morph_entries = [e for e in self._gpu_morph_entries
                                   if not e['np'].is_empty()]
        for entry in self._gpu_morph_entries:
            live = []
            for row, _name, slider in entry['sliders']:
                v = slider.get_value()
                if abs(v) > self._MORPH_EPS:
                    live.append((row, v))
            if len(live) > self._MORPH_LIVE_SLOTS:
                live.sort(key=lambda rv: -abs(rv[1]))
                live = live[:self._MORPH_LIVE_SLOTS]
                if not entry['warned']:
                    entry['warned'] = True
                    print(f'[Pax3DRender] set_gpu_morphs: '
                          f'{entry["np"].get_name()} drives more than '
                          f'{self._MORPH_LIVE_SLOTS} sliders at once; '
                          f'keeping the largest |weight| ones')
            key = tuple(live)
            if key == entry['last']:
                continue
            entry['last'] = key
            pta = entry['pta']
            for i in range(self._MORPH_LIVE_SLOTS):
                if i < len(live):
                    pta.set_element(
                        i, p3d.LVecBase2f(float(live[i][0]),
                                          float(live[i][1])))
                else:
                    pta.set_element(i, p3d.LVecBase2f(0.0, 0.0))

    def set_sun_light_mode(self, mode):
        """Switch between 'uniforms' (legacy) and 'directional' (real
        DirectionalLight) at runtime. Recompiles the PBR shader."""
        if mode not in ('uniforms', 'directional'):
            print(f'[Pax3DRender] Unknown sun_light_mode "{mode}", ignoring')
            return
        if mode == self.sun_light_mode:
            return
        self.sun_light_mode = mode
        if mode == 'directional':
            self._create_sun_light()
        else:
            self._destroy_sun_light()
        self._recompile_pbr()
        self.update_sun(self._last_sun_dir, self._last_sun_color)

    def set_enable_shadows(self, enabled):
        """Toggle sun shadow mapping at runtime (directional mode only —
        the legacy uniform sun has no light node to cast from)."""
        if enabled == self.enable_shadows:
            return
        self.enable_shadows = enabled
        self._recompile_pbr()
        if self.sun_light_np is not None:
            self._configure_sun_shadows(enabled)

    def set_srgb_inputs(self, enabled):
        """EXPERIMENT (Session R / R1.3): linearize color inputs at
        sample time by flagging base-color (M_modulate) and emission
        (M_emission) stage textures under render_node as sRGB formats.
        Data textures — normal (M_normal), metal-rough (M_selector),
        occlusion, LUTs — are untouched; only F_rgb -> F_srgb and
        F_rgba -> F_srgb_alpha conversions are made.

        This is the input half of the R1 color contract (Session A
        finding: ACES looks washed out because inputs are sampled RAW,
        not because of the tonemap). All game content is tuned around
        raw sampling + Hejl-Dawson, so the DEFAULT stays off and the
        game flips it only with content sign-off.

        Enabling walks the CURRENT subtree; content loaded later is not
        auto-converted — call set_srgb_inputs(True) again after loading
        (idempotent: already-converted textures are skipped). Disabling
        restores every converted texture's original format exactly
        (byte-identical opt-out — paxtest test_srgb). Returns the number
        of textures converted by this call."""
        enabled = bool(enabled)
        if enabled:
            first = not self._srgb_inputs
            self._srgb_inputs = True
            n = self._srgb_convert_subtree()
            if self._debug and (first or n):
                print(f'[Pax3DRender] srgb_inputs: {n} textures '
                      f'converted to sRGB formats')
            return n
        if not self._srgb_inputs:
            return 0
        self._srgb_inputs = False
        for tex, fmt in self._srgb_converted:
            tex.set_format(fmt)
            tex.release_all()
        n = len(self._srgb_converted)
        self._srgb_converted = []
        if self._debug:
            print(f'[Pax3DRender] srgb_inputs off: {n} texture formats '
                  f'restored')
        return n

    def _srgb_convert_subtree(self):
        converted = 0
        color_modes = (p3d.TextureStage.M_modulate,
                       p3d.TextureStage.M_emission)
        for np_ in self.render_node.find_all_matches('**'):
            for stage in np_.find_all_texture_stages():
                if stage.get_mode() not in color_modes:
                    continue
                tex = np_.get_texture(stage)
                if tex is None:
                    continue
                fmt = tex.get_format()
                new = None
                if fmt in (p3d.Texture.F_rgb, p3d.Texture.F_rgb8):
                    new = p3d.Texture.F_srgb
                elif fmt in (p3d.Texture.F_rgba, p3d.Texture.F_rgba8):
                    new = p3d.Texture.F_srgb_alpha
                if new is not None:
                    self._srgb_converted.append((tex, fmt))
                    tex.set_format(new)
                    # Already-prepared textures keep their old internal
                    # format until re-uploaded — release so the sRGB
                    # internal format actually reaches the GPU.
                    tex.release_all()
                    converted += 1
        return converted

    def set_enable_log_depth(self, enabled):
        """Toggle logarithmic depth at runtime (R4.1). Recompiles the PBR
        shader. The caller owns the lens: widen near/far (e.g. 0.1 / 1e9)
        when enabling, restore when disabling.

        A live viewmodel in depth_mode='range' is DEGRADED to 'clear'
        when log depth turns on (gl_FragDepth is clamped, not rescaled,
        by the region depth range — 'range' cannot work under
        LOG_DEPTH), loudly: the same warning as the registration-time
        fallback, and `visibility_query_valid` flips False so queries
        fail closed (2026-07-27, paxcraft ask). The degrade is one-way —
        re-register the viewmodel to get 'range' back after turning log
        depth off."""
        if enabled == self.enable_log_depth:
            return
        self.enable_log_depth = enabled
        if enabled:
            for reg in self._scene_cameras:
                if not (getattr(reg, 'is_viewmodel', False)
                        and reg.depth_range is not None):
                    continue
                reg.depth_range = None
                reg.clear_depth = True
                if reg.display_region is not None:
                    reg.display_region.set_depth_range(0.0, 1.0)
                    reg.display_region.set_clear_depth_active(True)
                msg = (f'[Pax3DRender] enable_log_depth: live viewmodel '
                       f'"{reg.name}" depth_mode="range" DEGRADED to '
                       f'"clear" (gl_FragDepth is clamped, not '
                       f'rescaled, by the region depth range)')
                if self.enable_visibility_query:
                    msg += (' — VISIBILITY QUERIES ARE NOW BLIND and '
                            'fail closed (visibility 0.0, .valid '
                            'False)')
                print(msg)
        self._recompile_pbr()

    def set_double_sided_lighting(self, enabled):
        """Toggle double-sided lighting at runtime (Session K).
        Recompiles the PBR shader (glass variants track it too).

        When on, backfaces of two-sided geometry are shaded with the
        inverted normal — the glTF `doubleSided` semantic — so a thin
        panel, decal, or interior wall seen from behind lights from the
        side actually facing the sun instead of rendering near-black.
        Front faces are untouched (the flip is a per-triangle-facing
        branch), so single-sided content cannot change. Off (default)
        is byte-identical to the shipped shader."""
        enabled = bool(enabled)
        if enabled == self.double_sided_lighting:
            return
        self.double_sided_lighting = enabled
        self._recompile_pbr()

    def set_enable_spot_exponent(self, enabled):
        """Toggle the per-light spot penumbra read (Session AF — flood
        lamps). Recompiles the PBR shader (variants track it).

        When on, every Spotlight's `set_exponent()` value applies with
        GL_SPOT_EXPONENT semantics — pow(cos angle-to-axis, exponent)
        inside the cone. Exponent 0 = the flag-off flat cone exactly
        (arithmetic no-op, gated); flood lamps want 1-4 for a soft
        center-weighted wash. BEWARE Panda's Spotlight class default is
        exponent 50 (a tight beam): set your spots' exponents
        deliberately before enabling, or existing cones retighten. Off
        (default) is byte-identical to the shipped shader — point and
        directional lights are never affected either way."""
        enabled = bool(enabled)
        if enabled == self.enable_spot_exponent:
            return
        self.enable_spot_exponent = enabled
        self._recompile_pbr()

    def update_sun(self, sun_dir_world, sun_color):
        """Update the sun. Same signature in both modes.

        Args:
            sun_dir_world: Vec3, world-space direction toward the sun
                           (normalized). Passed raw in Panda3D Z-up space.
            sun_color: Vec3, linear RGB color * intensity
        """
        self._last_sun_dir = p3d.Vec3(sun_dir_world)
        self._last_sun_color = p3d.Vec3(sun_color)

        if self.sun_light_mode == 'directional' and self.sun_light_np is not None:
            # Orient the NODE so its +Y forward is the photon travel
            # direction. The engine derives the shader's toward-light vector
            # from (default _direction) x (node transform), and the shadow
            # camera looks along the node's forward — so both stay in
            # agreement. (set_direction() would move the lighting but NOT
            # the shadow camera; never use it here.)
            travel = -p3d.Vec3(sun_dir_world)
            if travel.length_squared() > 0:
                travel.normalize()
                heading = math.degrees(math.atan2(-travel.x, travel.y))
                horiz = math.sqrt(travel.x * travel.x + travel.y * travel.y)
                pitch = math.degrees(math.atan2(travel.z, horiz))
                self.sun_light_np.set_hpr(heading, pitch, 0)
            self.sun_light_np.node().set_color(
                p3d.LColor(sun_color[0], sun_color[1], sun_color[2], 1))
            # The texel-snap grid rotates with the light's film axes — with
            # snapping on, re-derive the snapped center from the stored
            # ideal one (no-op set_pos when snapping is off).
            if self.shadow_texel_snap:
                self._apply_shadow_center()
            self._push_shadow_probe_matrix()

        # Uniforms are always updated: the legacy sun block reads them, and
        # the shader debug modes (V key) visualize them in both modes.
        self.render_node.set_shader_input('u_sun_dir_world', sun_dir_world)
        self.render_node.set_shader_input('u_sun_color', sun_color)

        # Float components (for debug mode 9) — also raw Z-up
        self.render_node.set_shader_input('u_sun_dir_x', float(sun_dir_world[0]))
        self.render_node.set_shader_input('u_sun_dir_y', float(sun_dir_world[1]))
        self.render_node.set_shader_input('u_sun_dir_z', float(sun_dir_world[2]))

    def set_debug_lighting(self, mode):
        """Set shader debug visualization mode (see pax_pbr.frag)."""
        self.render_node.set_shader_input('u_debug_lighting', float(mode))

    # ------------------------------------------------------------------
    # Planetside atmosphere (Session J / R5.1) — aerial perspective
    # ------------------------------------------------------------------

    def _push_atmosphere_uniforms(self):
        """Push the aerial-perspective uniforms.

        Always pushed (whether or not ENABLE_ATMOSPHERE is compiled in):
        unused inputs are free, whereas a compiled-in shader with a missing
        input is the known crash class (arch doc §3).
        """
        haze = self.atmo_haze_color
        sun_haze = (self.atmo_sun_haze_color
                    if self.atmo_sun_haze_color is not None else haze)
        rn = self.render_node
        rn.set_shader_input('u_atmo_haze_color', p3d.Vec3(*haze))
        rn.set_shader_input('u_atmo_sun_haze_color', p3d.Vec3(*sun_haze))
        rn.set_shader_input('u_atmo_sun_power', self.atmo_sun_power)
        rn.set_shader_input('u_atmo_density', self.atmo_density)
        rn.set_shader_input('u_atmo_inv_scale_height',
                            1.0 / self.atmo_scale_height)
        rn.set_shader_input('u_atmo_base_height', self.atmo_base_height)

    def set_enable_atmosphere(self, enabled):
        """Toggle aerial perspective / height haze (recompile-class).

        PLANETSIDE feature — leave off for space scenes (off is the
        default and is byte-identical to the pre-atmosphere pipeline).
        With it on, distant geometry fades into u_atmo_haze_color with an
        exponential-height falloff, tinted toward u_atmo_sun_haze_color
        when looking sunward. Tune with set_atmosphere_params().
        """
        enabled = bool(enabled)
        if enabled == self.enable_atmosphere:
            return
        self.enable_atmosphere = enabled
        self._recompile_pbr()

    def set_atmosphere_params(self, haze_color=None, sun_haze_color=None,
                              sun_power=None, density=None,
                              scale_height=None, base_height=None):
        """Update aerial-perspective parameters (uniform-only, no rebuild).

        haze_color:     linear-HDR inscatter color at the horizon. Match it
                        to the horizon of the scene's skybox.
        sun_haze_color: inscatter when looking straight at the sun (the
                        forward-scattering glow); None = follow haze_color.
        sun_power:      tightness of that sunward lobe (pow exponent).
        density:        extinction per world unit at base_height. The
                        distance to ~63% haze is 1/density world units.
        scale_height:   world-unit e-folding height of the medium — haze
                        thins with altitude (mountaintops stay clear).
        base_height:    world z of the density datum (ground level).
        """
        if haze_color is not None:
            self.atmo_haze_color = tuple(haze_color)
        if sun_haze_color is not None:
            self.atmo_sun_haze_color = tuple(sun_haze_color)
        if sun_power is not None:
            self.atmo_sun_power = float(sun_power)
        if density is not None:
            self.atmo_density = max(0.0, float(density))
        if scale_height is not None:
            self.atmo_scale_height = max(1e-6, float(scale_height))
        if base_height is not None:
            self.atmo_base_height = float(base_height)
        self._push_atmosphere_uniforms()

    # ------------------------------------------------------------------
    # Orbital scattering (Session R / R5.5) — planet limb + halo seen
    # from space
    # ------------------------------------------------------------------

    def _get_orbital_shaders(self):
        """The (extinction, inscatter) shader pair for the CURRENT
        pipeline defines (compiled lazily, invalidated by _recompile_pbr
        — same tracking rule as the glass variant)."""
        if self._orbital_shaders is None:
            base_defines = {                            'LOG_DEPTH': self.enable_log_depth}
            ext = shaderutils.make_shader(
                'pax_orbital_ext', 'orbital_atmo.vert', 'orbital_atmo.frag',
                dict(base_defines))
            ins_defines = dict(base_defines)
            ins_defines['ORB_INSCATTER'] = True
            ins = shaderutils.make_shader(
                'pax_orbital_ins', 'orbital_atmo.vert', 'orbital_atmo.frag',
                ins_defines)
            self._orbital_shaders = (ext, ins)
        return self._orbital_shaders

    def _reapply_orbital_shaders(self):
        """Re-push the (freshly invalidated) shader pair onto every
        registered orbital-atmosphere quad after a pipeline recompile."""
        live = []
        for entry in self._orbital_atmos:
            if entry['planet'].is_empty():
                entry['holder'].remove_node()
                continue
            live.append(entry)
        self._orbital_atmos = live
        if not live:
            return
        ext, ins = self._get_orbital_shaders()
        for entry in live:
            entry['ext_np'].set_shader(ext)
            entry['ins_np'].set_shader(ins)

    def set_orbital_atmosphere(self, planet_np, planet_radius=None,
                               scale_height=None, thickness=None,
                               density=None, scatter_tint=None,
                               intensity=None):
        """Give a planet an atmosphere as seen FROM SPACE: limb glow, a
        halo beyond the disk, aerial haze over the disk, and terminator
        tinting (R5.5, the spaceflight half of the R5 signature look).

        Single scattering through an exponential shell, rendered as a
        camera-facing quad pair (extinction, then additive inscatter)
        the pipeline places over the planet every frame — no recompile
        of anything, per-planet, unlimited planets. First call registers
        (planet_radius required); later calls update any subset of
        parameters (uniform-only). Unregistered = byte-identical scene
        (paxtest test_orbital opt-out checks; density=0 is also an exact
        no-op).

        Args:
            planet_np:     NodePath whose ORIGIN is the planet center.
                           Its world position is tracked every frame;
                           radii below are WORLD units (node scale is
                           not tracked — pass scaled-up values instead).
            planet_radius: sphere radius, world units. REQUIRED on the
                           first call.
            scale_height:  e-folding altitude H of the density falloff.
                           Default 0.02 * radius — a stylized ~15x
                           thicker than Earth-true (0.0013 * R), which
                           reads as a visible limb at game distances.
            thickness:     shell top above the surface. Default 6 * H
                           (density 0.25% of surface — visually black).
            density:       extinction per world unit at the surface
                           (scalar; per-channel via scatter_tint).
                           Default 4 / sqrt(2*pi*R*H), which puts the
                           tangent-ray optical depth at ~4 * tint per
                           channel — an Earth-like limb for any radius.
            scatter_tint:  relative per-channel scattering (the color
                           physics). Default (0.175, 0.41, 1.0) —
                           Rayleigh lambda^-4 for RGB — gives blue haze
                           over the disk and a reddened terminator.
                           Mars-ish dust: try (1.0, 0.55, 0.35).
            intensity:     inscatter brightness multiplier (the phase
                           function is normalized to sphere-average 1,
                           so this scales mean halo brightness against
                           u_sun_color directly).

        Boundary with the planetside haze (R5.1): this is the ORBITAL
        half only. It composes with scene content between camera and
        planet imperfectly (objects INSIDE the shell get full-path haze
        drawn over them — the quad sits at the shell's near surface).
        The fly-down handoff to enable_atmosphere is game-paced R4.2-era
        work: pick a handoff altitude and cross-fade density there.
        """
        entry = next((e for e in self._orbital_atmos
                      if e['planet'] == planet_np), None)
        if entry is None:
            if planet_radius is None:
                raise ValueError('set_orbital_atmosphere needs '
                                 'planet_radius on first registration')
            entry = self._make_orbital_entry(planet_np)
            self._orbital_atmos.append(entry)
        if planet_radius is not None:
            entry['radius'] = float(planet_radius)
        if scale_height is not None:
            entry['scale_height'] = max(1e-6, float(scale_height))
        if thickness is not None:
            entry['thickness'] = max(1e-6, float(thickness))
        if density is not None:
            entry['density'] = max(0.0, float(density))
        if scatter_tint is not None:
            entry['tint'] = tuple(scatter_tint)
        if intensity is not None:
            entry['intensity'] = float(intensity)
        self._push_orbital_uniforms(entry)
        # Place immediately so the registration frame renders correctly
        # (the per-frame task keeps it updated afterwards).
        self._place_orbital_quads(
            entry, self.camera_node.get_pos(self.render_node))

    def clear_orbital_atmosphere(self, planet_np):
        """Undo set_orbital_atmosphere() for this planet: the quads are
        removed and the scene graph is restored exactly (byte-identical
        opt-out — paxtest test_orbital)."""
        entry = next((e for e in self._orbital_atmos
                      if e['planet'] == planet_np), None)
        if entry is None:
            return
        entry['holder'].remove_node()
        self._orbital_atmos.remove(entry)

    def _make_orbital_entry(self, planet_np):
        """Build the quad pair for one planet: extinction (multiplies the
        framebuffer by per-channel transmittance) then inscatter
        (additive), both depth-tested but not depth-written, drawn after
        the opaque scene in the 'fixed' bin."""
        holder = self.render_node.attach_new_node('pax3d_orbital_atmo')
        # Never rasterize into the sun's shadow map (see ORBITAL_HIDE_BIT)
        holder.hide(p3d.DrawMask.bit(self.ORBITAL_HIDE_BIT))
        cm = p3d.CardMaker('pax3d_orbital_quad')
        cm.set_frame(-1, 1, -1, 1)
        ext_np = holder.attach_new_node(cm.generate())
        ins_np = holder.attach_new_node(cm.generate())
        sort_base = self._orbital_sort_next
        self._orbital_sort_next += 2
        ext, ins = self._get_orbital_shaders()
        for quad, shader, sort, blend in (
                (ext_np, ext, sort_base, p3d.ColorBlendAttrib.make(
                    p3d.ColorBlendAttrib.M_add,
                    p3d.ColorBlendAttrib.O_zero,
                    p3d.ColorBlendAttrib.O_incoming_color)),
                (ins_np, ins, sort_base + 1, p3d.ColorBlendAttrib.make(
                    p3d.ColorBlendAttrib.M_add,
                    p3d.ColorBlendAttrib.O_one,
                    p3d.ColorBlendAttrib.O_one))):
            quad.set_shader(shader)
            quad.set_bin('fixed', sort)
            quad.set_depth_write(False)
            quad.set_two_sided(True)
            quad.set_attrib(blend)
        return {
            'planet': planet_np,
            'holder': holder,
            'ext_np': ext_np,
            'ins_np': ins_np,
            'radius': 1.0,
            'scale_height': None,   # None = derived default
            'thickness': None,
            'density': None,
            'tint': (0.175, 0.41, 1.0),
            'intensity': 1.0,
        }

    def _orbital_resolved(self, entry):
        """(radius, scale_height, top_radius, density) with the
        documented defaults derived from the radius."""
        radius = entry['radius']
        h = entry['scale_height']
        if h is None:
            h = 0.02 * radius
        thickness = entry['thickness']
        if thickness is None:
            thickness = 6.0 * h
        density = entry['density']
        if density is None:
            density = 4.0 / math.sqrt(2.0 * math.pi * radius * h)
        return radius, h, radius + thickness, density

    def _push_orbital_uniforms(self, entry):
        radius, h, top, density = self._orbital_resolved(entry)
        entry['_top'] = top
        tint = entry['tint']
        holder = entry['holder']
        holder.set_shader_input('u_orb_planet_radius', radius)
        holder.set_shader_input('u_orb_top_radius', top)
        holder.set_shader_input('u_orb_inv_scale_height', 1.0 / h)
        holder.set_shader_input(
            'u_orb_beta', p3d.Vec3(density * tint[0], density * tint[1],
                                   density * tint[2]))
        holder.set_shader_input('u_orb_intensity', entry['intensity'])

    def _place_orbital_quads(self, entry, cam_pos):
        """Aim and size one planet's quad pair for this frame's camera:
        the quad sits at the shell's near surface (in front of every
        in-shell depth), faces the camera, and covers the shell's
        projected disc with margin. Falls back to a near-camera
        fullscreen quad when the camera is inside/near the shell."""
        center = entry['planet'].get_pos(self.render_node)
        holder = entry['holder']
        holder.set_shader_input('u_orb_center', center)
        to_c = center - cam_pos
        dist = to_c.length()
        if dist <= 1e-6:
            return
        u = to_c / dist
        top = entry.get('_top') or self._orbital_resolved(entry)[2]
        near = self.camera_node.node().get_lens().get_near()
        quad_dist = max(dist - top * 1.05, near * 2.0)
        holder.set_pos(cam_pos + u * quad_dist)
        up = (p3d.Vec3(0, 1, 0) if abs(u.z) > 0.99
              else p3d.Vec3(0, 0, 1))
        holder.look_at(p3d.Point3(cam_pos + u * (quad_dist + 1.0)), up)
        if dist > top * 1.05:
            sin_a = top / dist
            half = (sin_a / math.sqrt(max(1.0 - sin_a * sin_a, 1e-6))
                    ) * quad_dist * 1.1
        else:
            half = quad_dist * 6.0
        holder.set_scale(half)

    def _update_orbital_atmos(self, cam_pos):
        live = []
        for entry in self._orbital_atmos:
            if entry['planet'].is_empty():
                entry['holder'].remove_node()
                continue
            live.append(entry)
            self._place_orbital_quads(entry, cam_pos)
        self._orbital_atmos = live

    # ------------------------------------------------------------------
    # Environment-driven ambient (Session J / R5.2) — irradiance SH
    # ------------------------------------------------------------------

    def set_ambient_sh(self, coeffs, node=None):
        """Feed 9 irradiance-convolved SH coefficients (RGB triples) to the
        shader's existing sh_coeffs diffuse-IBL path (uniform-only).

        The shader evaluates E(n) = sum(coeffs[i] * Y_i(n)) and applies it
        as base_color * E(n) / pi, energy-conserving against metallic/
        Fresnel (arch doc §9 R5 hooks). Basis slot order (world frame,
        Panda Z-up): [const, x, z, y, xz, yz, xy, 3z^2-1, x^2-y^2] with
        simplepbr's normalization constants. Survives shader recompiles.

        node (Session S): bind to a SUBTREE instead of the whole scene —
        an inherited shader-input override, so e.g. a hull interior gets
        cabin-derived ambient while the exterior keeps the sky's. The
        global set stays tracked and re-pushed across recompiles;
        node-level inputs live on the node and survive on their own.
        clear_ambient_sh(node=np) reverts the subtree to the inherited
        (global) set, byte-identical.
        """
        pta = p3d.PTA_LVecBase3f()
        for c in coeffs:
            pta.push_back(p3d.LVecBase3f(c[0], c[1], c[2]))
        if len(pta) != 9:
            raise ValueError(f'set_ambient_sh needs 9 coefficients, '
                             f'got {len(pta)}')
        if node is not None:
            node.set_shader_input('sh_coeffs', pta)
            return
        self._ambient_sh = pta
        self.render_node.set_shader_input('sh_coeffs', pta)

    def set_hemisphere_ambient(self, sky_color, ground_color, up=(0, 0, 1),
                               node=None):
        """Two-tone environment ambient: sky_color lights up-facing
        surfaces, ground_color down-facing, smoothly blended by the world
        normal (uniform-only, exact SH bands 0-1).

        THE cheap planetside-look win: shadowed sides of objects pick up
        sky tint instead of a flat gray, and undersides get ground bounce.
        Both colors are linear; a surface facing straight up receives
        base_color * (avg + 2/3 * delta) where avg/delta are the mean and
        half-difference of the two colors. Replaces (don't stack with) the
        flat AmbientLight the scene would otherwise use — keep any
        AmbientLight small. up is the world up axis in Panda Z-up space.
        clear_ambient_sh() restores the exact pre-call output.
        node (Session S): apply to a subtree only — see set_ambient_sh.
        """
        sky = p3d.Vec3(sky_color[0], sky_color[1], sky_color[2])
        ground = p3d.Vec3(ground_color[0], ground_color[1], ground_color[2])
        upv = p3d.Vec3(up[0], up[1], up[2])
        if upv.length_squared() > 0:
            upv.normalize()
        avg = (sky + ground) * 0.5
        half = (sky - ground) * 0.5
        # Irradiance of L(w) = avg + half*(w.up): E(n) = pi*avg
        # + (2pi/3)*half*(n.up). Divide by the shader's basis constants so
        # sum(c_i * Y_i(n)) reproduces E(n) exactly (bands 0-1 are exact
        # for a linear-gradient environment; higher bands are zero).
        c0 = avg * (math.pi / 0.282095)
        lin = half * ((2.0 * math.pi / 3.0) / 0.488603)
        zero = (0.0, 0.0, 0.0)
        self.set_ambient_sh([
            tuple(c0),
            tuple(lin * upv.x),   # slot 1: basis normal.x
            tuple(lin * upv.z),   # slot 2: basis normal.z
            tuple(lin * upv.y),   # slot 3: basis normal.y
            zero, zero, zero, zero, zero,
        ], node=node)

    def clear_ambient_sh(self, node=None):
        """Remove the environment ambient: sh_coeffs back to zeros —
        byte-identical to the pipeline before any set_*_ambient call.
        With node (Session S): remove only the subtree override — the
        subtree reverts to the INHERITED (global) coefficients."""
        if node is not None:
            node.clear_shader_input('sh_coeffs')
            return
        self._ambient_sh = None
        self.render_node.set_shader_input('sh_coeffs', self._empty_sh)

    def set_env_map(self, cubemap, max_lod=None, node=None):
        """Bind a cubemap for specular IBL reflections (Session M /
        R5.3 first slice) — glass canopies and metallic hulls pick up
        the environment; rough surfaces reflect it blurred.

        The shader samples `textureCubeLod(env, reflect_dir,
        perceptual_roughness * max_lod)`: roughness 0 reads mip 0,
        roughness 1 the top of the ladder. FIRST SLICE CONTRACT: the
        cubemap's own mip chain IS the roughness ladder. A properly
        GGX-prefiltered chain (offline bake) is the correct input; an
        ordinary cubemap works too — mipmap filtering is enforced here
        and auto-generated box mips stand in as an approximation
        (visually fine for blurry-metal use; a prefilter tool is future
        R5 work). Pair with the diffuse half from the same source:
        `set_ambient_sh(sh_from_cubemap(cubemap))`.

        max_lod defaults to the full chain (log2 of the base size);
        pass a smaller value to pin roughness 1 at a coarser mip of a
        partially-filtered chain. Uniform-cost; survives recompiles;
        scaled per-node by set_ambient_scale (reflections are indirect
        light); reflections ride at full strength on set_glass nodes.

        node (Session S): bind to a SUBTREE instead of the whole scene
        — an inherited shader-input override, so a hull interior
        reflects a cabin-derived map while the exterior keeps the sky
        (the walkable-ship pattern; pair with the node= form of
        set_ambient_sh from the same cubemap). max_reflection_lod is
        overridden on the same node so the interior chain's ladder is
        addressed correctly. clear_env_map(node=np) reverts the
        subtree to the inherited (global) map, byte-identical.
        """
        if cubemap is None:
            self.clear_env_map(node=node)
            return
        if cubemap.get_texture_type() != p3d.Texture.TT_cube_map:
            raise ValueError('set_env_map needs a cube map Texture')
        if self._brdf_lut.get_x_size() <= 1:
            # The white fallback LUT makes lut.y = 1: the whole env
            # color would be ADDED to every surface. Refuse loudly.
            raise RuntimeError(
                'set_env_map needs the real BRDF LUT '
                '(pax3d_render/textures/brdf_lut.txo — generate with '
                'tools/gen_brdf_lut.py)')
        if not p3d.SamplerState.is_mipmap(cubemap.get_minfilter()):
            cubemap.set_minfilter(p3d.SamplerState.FT_linear_mipmap_linear)
        if max_lod is None:
            max_lod = max(0, int(math.log2(max(cubemap.get_x_size(), 1))))
        if node is not None:
            node.set_shader_input('filtered_env_map', cubemap)
            node.set_shader_input('max_reflection_lod', float(max_lod))
            return
        self._env_map = cubemap
        self._env_map_lod = float(max_lod)
        self._set_env_map_uniforms()

    def clear_env_map(self, node=None):
        """Remove the specular IBL cubemap: back to the 1x1 black
        default — byte-identical to the pipeline before set_env_map.
        With node (Session S): remove only the subtree override — the
        subtree reverts to the INHERITED (global) map and lod."""
        if node is not None:
            node.clear_shader_input('filtered_env_map')
            node.clear_shader_input('max_reflection_lod')
            return
        self._env_map = None
        self._env_map_lod = 0
        self._set_env_map_uniforms()

    def set_env_scale(self, nodepath, scale):
        """Scale ONLY the specular env-map reflection term for
        `nodepath` and its subtree (Round-5 ask). Unlike
        set_ambient_scale (which damps SH diffuse + flat ambient too),
        this touches nothing but ibl_spec — stylised geometry keeps a
        TRACE of sky sheen (e.g. terrain at ~0.15) instead of the
        binary black-cube exclusion. Inherits down the subtree,
        survives recompiles, composes multiplicatively with the global
        set_env_intensity. Root default 1.0 = exact no-op."""
        nodepath.set_shader_input('u_env_scale', float(scale))

    def clear_env_scale(self, nodepath):
        """Undo set_env_scale(): the subtree reverts to the inherited
        (root default 1.0) env scale, byte-identical to untouched."""
        nodepath.clear_shader_input('u_env_scale')

    def set_env_intensity(self, intensity):
        """Global multiplier on the specular env-map term (Round-5
        ask): within a held sky segment the game ramps sky brightness
        (midday bell, dusk darken) and crossfades skyboxes — SH tracks
        that game-side (linear coefficients); this lets specular track
        it too. Multiplies with any per-node set_env_scale. 1.0 =
        exact no-op."""
        self._env_intensity = float(intensity)
        self.render_node.set_shader_input('u_env_intensity',
                                          self._env_intensity)

    def set_env_map_rotation(self, degrees):
        """Yaw the specular env-map lookup about world +Z (Round-5
        ask): the environment reads as rotated by `degrees` in the
        same sense as set_h(degrees) on a skybox dome — drift-rotating
        skies keep reflections in sync with the game-side yawed SH.
        0.0 = exact no-op (cos/sin (1, 0))."""
        self._env_yaw_deg = float(degrees)
        a = math.radians(self._env_yaw_deg)
        self.render_node.set_shader_input(
            'u_env_yaw', p3d.LVecBase2(math.cos(a), -math.sin(a)))

    # ------------------------------------------------------------------
    # Per-frame update
    # ------------------------------------------------------------------

    def _update(self, task):
        """Per-frame maintenance: shadow shaders, camera position, clear color."""
        # Handle shadow casters (same as simplepbr)
        if self.enable_shadows:
            for caster in self._get_all_casters():
                if isinstance(caster, p3d.PointLight):
                    caster.set_shadow_caster(False)
                    continue
                state = caster.get_initial_state()
                if not state.has_attrib(p3d.ShaderAttrib):
                    attr = self._create_shadow_shader_attrib()
                    state = state.add_attrib(attr, 1)
                    state = state.remove_attrib(p3d.CullFaceAttrib)
                    caster.set_initial_state(state)
                    # ER-014: (re)built initial state means the shadow
                    # shader may have changed — keep the tag-state
                    # rescue in step (also covers casters that appear
                    # after the tag went active).
                    if self._detail_shadow_tag_active:
                        self._sync_caster_tag_state(caster)

        # Copy background color to offscreen buffer
        if self._filtermgr.buffers:
            self._filtermgr.buffers[0].set_clear_color(
                self.window.get_clear_color())

        # Camera world position for IBL reflections — raw Z-up, no CS conversion
        cam_pos = self.camera_node.get_pos(self.render_node)
        self.render_node.set_shader_input('camera_world_position', cam_pos)

        # Orbital-atmosphere quads follow the camera (R5.5)
        if self._orbital_atmos:
            self._update_orbital_atmos(cam_pos)

        # Powered displays (ER-005) + blinkers: UV scroll, flipbook, and
        # blink stepping. O(active) per frame (blink pushes are
        # edge-triggered); zero when the registries are empty.
        if self._uv_scrolls or self._flipbooks or self._blinks:
            now = p3d.ClockObject.get_global_clock().get_frame_time()
            if self._uv_scrolls:
                self._uv_scrolls = [e for e in self._uv_scrolls
                                    if not e[0].is_empty()]
                for np_, du, dv in self._uv_scrolls:
                    np_.set_shader_input(
                        'u_uv_transform',
                        p3d.LVecBase4((du * now) % 1.0, (dv * now) % 1.0,
                                      1.0, 1.0))
            if self._flipbooks:
                self._flipbooks = [e for e in self._flipbooks
                                   if not e['np'].is_empty()]
                for entry in self._flipbooks:
                    self._step_flipbook(entry, now)
            if self._blinks:
                self._blinks = [e for e in self._blinks
                                if not e['np'].is_empty()]
                for entry in self._blinks:
                    self._step_blink(entry, now)

        # Light halos (Session AF, ER-013): keep the viewport-height
        # uniform current (resize) and prune dead nodes. O(halos), zero
        # when the registry is empty.
        if self._halo_nodes:
            self._halo_nodes = [e for e in self._halo_nodes
                                if not e['np'].is_empty()
                                and not e['quad'].is_empty()]
            vp_h = float(max(1, self.window.get_y_size()))
            if vp_h != self._halo_vp_h:
                self._halo_vp_h = vp_h
                self.render_node.set_shader_input('u_halo_vp_h', vp_h)

        # Visibility queries (Session AF): read last frame's results,
        # push this frame's target projections. O(queries).
        if self._vis_buffer is not None:
            self._step_visibility_queries()

        # Effect sprites (Session AD): reap completed one-shots — the
        # held last frame is transparent, but the draw call and the
        # screen/glass/flipbook registrations must not outlive playback.
        if self._effects:
            now = p3d.ClockObject.get_global_clock().get_frame_time()
            live = []
            for entry in self._effects:
                done = (entry['np'].is_empty()          # game removed it
                        or (entry['end'] is not None
                            and now >= entry['end']))   # playback over
                if done:
                    self._cleanup_effect(entry['np'])
                    continue
                if entry['fade'] > 0.0:
                    # spawn_effect(fade_out=...): coverage + emission
                    # ramp to zero across the last fade seconds, so
                    # footage with a non-transparent final frame never
                    # holds a ghost card then pops off.
                    k = min((entry['end'] - now) / entry['fade'], 1.0)
                    k = max(k, 0.0)
                    if k != entry['fade_k']:
                        entry['fade_k'] = k
                        entry['np'].set_alpha_scale(k)
                        self.set_emission_scale(entry['np'], k)
                live.append(entry)
            self._effects = live

        # ER-010 wet-sand breathing edge: per-frame phase push,
        # O(animated terrain nodes); zero while no shore breathes or
        # every phase is pinned (anim_phase — the determinism valve).
        if self._terrain_water_anim:
            now = p3d.ClockObject.get_global_clock().get_frame_time()
            self._terrain_water_anim = [
                e for e in self._terrain_water_anim
                if not e[0].is_empty()]
            tau = 6.28318530718
            for np_, water in self._terrain_water_anim:
                phase = (tau * now / water['anim_period']) % tau
                np_.set_shader_input(
                    'u_terrain_water2',
                    p3d.LVecBase4(water['sat'], water['anim_amp'],
                                  1.0 / water['anim_scale'], phase))

        # ER-008 local light budgets: re-score and rebind on change
        if self._light_budgets:
            self._step_light_budgets()

        # GPU morphs (Session Z): per-character slider push, O(sliders)
        if self._gpu_morph_entries:
            self._step_gpu_morphs()

        # Log-depth coefficient tracks the camera lens far plane (R4.1) —
        # the game may change near/far at runtime (regime switches)
        if self.enable_log_depth:
            far = max(2.0, self.camera_node.node().get_lens().get_far())
            self.render_node.set_shader_input(
                'u_log_depth_coef', 1.0 / math.log2(1.0 + far))

        # SSAO reconstructs positions from the lens — track it per frame
        if self._ssao_quad is not None:
            self._push_ssao_lens_inputs(self._ssao_quad)

        # TAA per-frame jitter
        if self.enable_taa and self._taa_resolve_quad is not None:
            self._taa_jitter_index += 1
            lens = self.camera_node.node().get_lens()
            jx = self._halton(self._taa_jitter_index, 2) - 0.5
            jy = self._halton(self._taa_jitter_index, 3) - 0.5
            win_x = max(1, self.window.get_x_size())
            win_y = max(1, self.window.get_y_size())
            film_size = lens.get_film_size()
            lens.set_film_offset(
                jx * film_size.x / win_x,
                jy * film_size.y / win_y
            )
            self._taa_frame += 1
            self._taa_resolve_quad.set_shader_input(
                'u_taa_frame', float(self._taa_frame))

        return task.DS_cont

    def _get_all_casters(self):
        """Find all shadow-casting lights in the scene."""
        engine = p3d.GraphicsEngine.get_global_ptr()
        cameras = [
            dr.camera
            for win in engine.windows
            for dr in win.active_display_regions
        ]

        result = []
        for cam_np in cameras:
            if cam_np.is_empty():
                continue
            node = cam_np.node()
            if hasattr(node, 'is_shadow_caster') and node.is_shadow_caster():
                result.append(node)
        return result

    def _make_shadow_shader(self):
        """The depth-pass shader for the CURRENT pipeline defines
        (shared by the caster initial states and the ER-014 tag
        states)."""
        defines = {
            'ENABLE_SKINNING': self.enable_hardware_skinning,
            'MAX_SKINNING_BONES': self.max_skinning_bones,
            # ER-002: with any instanced node registered, the depth pass
            # carries the same instancing path (identity fallback keeps
            # non-instanced casters behavior-identical).
            'INSTANCING': bool(self._instanced_nodes),
        }
        return shaderutils.make_shader(
            'shadow', 'shadow.vert', 'shadow.frag', defines
        )

    def _create_shadow_shader_attrib(self):
        """Create a shader attrib for shadow-casting geometry."""
        attr = p3d.ShaderAttrib.make(self._make_shadow_shader())
        if self.enable_hardware_skinning:
            attr = attr.set_flag(p3d.ShaderAttrib.F_hardware_skinning, True)
        if self._instanced_nodes:
            attr = attr.set_flag(
                p3d.ShaderAttrib.F_hardware_instancing, True)
        return attr

    # ------------------------------------------------------------------
    # Cleanup
    # ------------------------------------------------------------------

    def cleanup(self):
        """Remove the pipeline task, sun light, aux cameras, FilterManager."""
        self.taskmgr.remove('pax3d_render_update')
        self._destroy_sun_light()
        for reg in list(self._scene_cameras):
            self.unregister_scene_camera(reg)
        if self.enable_taa:
            lens = self.camera_node.node().get_lens()
            lens.set_film_offset(0, 0)
        if self._filtermgr:
            self._filtermgr.cleanup()
