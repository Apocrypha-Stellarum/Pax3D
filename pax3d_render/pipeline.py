    def register_scene_camera(self, camera_np, sort=-100,
                              clear_color=(0, 0, 0, 1), clear_depth=True,
                              name='aux_scene_camera'):
        """Attach an auxiliary camera to the pipeline's scene buffer.

        The display region is owned by the pipeline and is automatically
        re-created whenever the internal FilterManager chain is rebuilt
        (bloom toggle, bloom_levels/TAA change, etc.) — external code never
        needs to locate the offscreen buffer itself.

        Args:
            camera_np: NodePath of a Camera node (caller owns lens, masks,
                       scene root, and transform).
            sort: display-region sort. Negative renders BEFORE the main
                  scene (background, e.g. a sky camera).
            clear_color: RGBA tuple to clear this region to, or None to
                         not clear color.
            clear_depth: whether this region clears depth before drawing.

        For any background camera (sort < 0), the main scene region is set
        to preserve background pixels: color clear off, depth clear on.

        Returns an opaque registration handle for unregister_scene_camera().
        """
        reg = _SceneCameraRegistration(camera_np, sort, clear_color,
                                       clear_depth, name)
        self._scene_cameras.append(reg)
        self._attach_scene_camera(reg)
        return reg

    def unregister_scene_camera(self, reg):
        """Detach an auxiliary camera previously registered."""
        if reg in self._scene_cameras:
            self._scene_cameras.remove(reg)
        if reg.display_region is not None and reg.buffer is not None:
            reg.buffer.remove_display_region(reg.display_region)
        reg.display_region = None
        reg.buffer = None
        self._update_main_region_clears()

    def register_viewmodel_camera(self, vm_root, near=0.02, far=8.0,
                                  fov=None, sort=100, depth_mode='clear',
                                  name='viewmodel', on_depth_degrade='warn'):
        """Foreground viewmodel region: the standard FPS solution for
        hands/weapons closer than the world camera's near plane.

        Draws `vm_root` (and only it) through a second camera with its own
        near/far, AFTER the world, into the same HDR scene buffer — so the
        full post chain (bloom, tonemap, TAA) applies to the viewmodel
        exactly as to the world. The world never sees the viewmodel: it is
        hidden from the main camera and from the sun shadow camera (draw
        bit VIEWMODEL_BIT is pipeline-reserved for this).

        Args:
            vm_root: NodePath holding the viewmodel subtree. Must live
                under the pipeline's render node for PBR lighting inputs
                to reach it — parenting it under the main camera NodePath
                is the usual choice (hands then track the view for free).
                The pipeline OWNS this subtree's visibility masks while
                registered; after unregister it is left fully hidden.
            near/far: the viewmodel lens planes (default 0.02/8.0 —
                hands at 4 cm render; keep far tight for depth precision).
            fov: horizontal FOV in degrees; None copies the main lens
                (falls back to 50 if the main lens is not perspective).
                Games often run the viewmodel a touch narrower than the
                world FOV — pass it explicitly to taste.
            sort: display-region sort; must stay > the main region's 0.
            depth_mode: 'clear' (default) clears the region's depth before
                drawing — the viewmodel always wins, but the scene buffer's
                depth texture is stomped full-screen (SSAO reads garbage
                world depth). 'range' compresses the viewmodel into window
                depth [0, 0.05] via glDepthRange — no clear, world depth
                survives outside the viewmodel silhouette (SSAO-friendly;
                hands get a near-field AO halo at their own pixels only).
                'range' requires enable_log_depth=False: under LOG_DEPTH
                the PBR shader writes gl_FragDepth, which GL clamps (not
                rescales) to the region's depth range — self-occlusion
                inside the viewmodel would flatten. Falls back to 'clear'
                with a warning in that case.
            on_depth_degrade: what to do when a 'range' request cannot be
                honored (log depth on, or no per-region depth range on
                stock 1.10). 'warn' (default) falls back to 'clear' with
                a loud boot warning; 'raise' raises RuntimeError instead —
                pass it when downstream systems (visibility queries, SSAO)
                depend on the world depth surviving, so a config change
                (e.g. enable_log_depth flipping on) fails at init instead
                of shipping a silent regression (the paxcraft Session-5
                three-session trap, filed 2026-07-27). Either way the
                degrade also flips `visibility_query_valid` False and
                forces every VisibilityQuery to fail closed (0.0).

        Returns a registration handle (reg.camera_np is the created
        viewmodel camera — parented under the main camera at identity;
        move/animate it for sway). Pass to unregister_viewmodel_camera().

        Caveats (measured, see test_viewmodel):
          * TAA jitters only the main camera lens; the viewmodel is
            unjittered (no ghosting, slightly less temporal AA on hands).
          * Other aux cameras whose camera_mask contains VIEWMODEL_BIT
            would also draw the viewmodel — keep bit 29 out of their
            masks (main + shadow cameras are handled automatically).
          * One viewmodel registration at a time is the supported shape.
        """
        if depth_mode not in ('clear', 'range'):
            raise ValueError(f'depth_mode must be "clear" or "range", '
                             f'got {depth_mode!r}')
        if on_depth_degrade not in ('warn', 'raise'):
            raise ValueError(f'on_depth_degrade must be "warn" or '
                             f'"raise", got {on_depth_degrade!r}')
        requested_depth_mode = depth_mode
        degrade_reason = None
        if depth_mode == 'range' and self.enable_log_depth:
            degrade_reason = ('incompatible with enable_log_depth '
                              '(gl_FragDepth is clamped, not rescaled, '
                              'by the region depth range)')
        elif (depth_mode == 'range'
                and not hasattr(p3d.DisplayRegion, 'set_depth_range')):
            # Stock 1.10 has no per-region depth range (1.11 API)
            degrade_reason = ('needs DisplayRegion.set_depth_range '
                              '(Panda3D 1.11+)')
        if degrade_reason is not None:
            msg = (f'[Pax3DRender] viewmodel depth_mode="range" '
                   f'{degrade_reason} — degrading to "clear"')
            if self.enable_visibility_query:
                msg += ('. VISIBILITY QUERIES ARE NOW BLIND: the '
                        'viewmodel region clears the scene depth '
                        'full-screen, so every query fails CLOSED '
                        '(visibility 0.0, .valid False; '
                        'pipeline.visibility_query_valid False)')
            if on_depth_degrade == 'raise':
                raise RuntimeError(msg + ' — on_depth_degrade="raise"')
            print(msg)
            depth_mode = 'clear'
        if not self.render_node.is_ancestor_of(vm_root):
            print(f'[Pax3DRender] WARNING: viewmodel root '
                  f'"{vm_root.get_name()}" is not under the pipeline '
                  f'render node — PBR lighting inputs will not reach it')

        win_w = max(1, self.window.get_x_size())
        win_h = max(1, self.window.get_y_size())
        lens = p3d.PerspectiveLens()
        lens.set_aspect_ratio(win_w / float(win_h))
        main_lens = self.camera_node.node().get_lens()
        if fov is not None:
            lens.set_fov(float(fov))
        elif isinstance(main_lens, p3d.PerspectiveLens):
            lens.set_fov(main_lens.get_fov()[0])
        else:
            lens.set_fov(50.0)
        lens.set_near_far(near, far)

        vm_bit = p3d.DrawMask.bit(self.VIEWMODEL_BIT)
        overall = p3d.DrawMask(p3d.PandaNode.get_overall_bit())
        cam = p3d.Camera(f'pax3d_{name}_camera')
        cam.set_lens(lens)
        cam.set_camera_mask(vm_bit)
        cam_np = self.camera_node.attach_new_node(cam)

        main_cam = self.camera_node.node()
        prev_main_mask = p3d.DrawMask(main_cam.get_camera_mask())
        main_cam.set_camera_mask(prev_main_mask & ~vm_bit)

        # World invisible to the viewmodel camera; the viewmodel subtree
        # overrides that ancestor hide and is itself visible on the
        # viewmodel bit ONLY (so the shadow camera — bit 29 always cleared
        # from its mask — never rasterizes it into the depth map).
        # show() first: a re-registered root still carries the overall
        # hide that unregister_viewmodel_camera leaves behind.
        vm_root.show()
        self.render_node.hide(vm_bit)
        vm_root.hide(p3d.DrawMask.all_on() & ~vm_bit & ~overall)
        vm_root.show_through(vm_bit)

        reg = _SceneCameraRegistration(
            cam_np, sort, None, depth_mode == 'clear', name,
            depth_range=(self.VIEWMODEL_DEPTH_RANGE
                         if depth_mode == 'range' else None))
        reg.is_viewmodel = True
        reg.requested_depth_mode = requested_depth_mode
        reg.vm_root = vm_root
        reg.prev_main_camera_mask = prev_main_mask
        self._scene_cameras.append(reg)
        self._attach_scene_camera(reg)
        if self._debug:
            print(f'[Pax3DRender] viewmodel "{name}" registered '
                  f'(near={near}, far={far}, depth_mode={depth_mode})')
        return reg

    def unregister_viewmodel_camera(self, reg):
        """Undo register_viewmodel_camera: removes the display region and
        camera, restores the main camera's mask and the world's draw bits.
        The viewmodel subtree is left FULLY HIDDEN — show()/reparent it
        yourself if you repurpose the nodes."""
        if not getattr(reg, 'is_viewmodel', False):
            raise ValueError('not a viewmodel registration — use '
                             'unregister_scene_camera for plain aux cameras')
        self.unregister_scene_camera(reg)
        if reg.camera_np is not None and not reg.camera_np.is_empty():
            reg.camera_np.remove_node()
        self.camera_node.node().set_camera_mask(reg.prev_main_camera_mask)
        vm_bit = p3d.DrawMask.bit(self.VIEWMODEL_BIT)
        if not any(getattr(r, 'is_viewmodel', False)
                   for r in self._scene_cameras):
            self.render_node.show(vm_bit)
        if not reg.vm_root.is_empty():
            reg.vm_root.hide()

    def _scene_buffer(self):
        buffers = getattr(self._filtermgr, 'buffers', None)
        return buffers[0] if buffers else None

    def _find_main_display_region(self):
        """The display region where the main camera renders on the buffer."""
        buf = self._scene_buffer()
        if buf is None:
            return None
        for i in range(buf.get_num_display_regions()):
            dr = buf.get_display_region(i)
            if dr.get_camera() == self.camera_node:
                return dr
        return None

    def _attach_scene_camera(self, reg):
        buf = self._scene_buffer()
        if buf is None:
            print(f'[Pax3DRender] WARNING: no scene buffer for aux camera '
                  f'"{reg.name}"')
            return
        dr = buf.make_display_region()
        dr.set_sort(reg.sort)
        dr.set_camera(reg.camera_np)
        if reg.clear_color is not None:
            dr.set_clear_color_active(True)
            dr.set_clear_color(p3d.LColor(*reg.clear_color))
        dr.set_clear_depth_active(reg.clear_depth)
        if reg.depth_range is not None:
            dr.set_depth_range(*reg.depth_range)
        reg.display_region = dr
        reg.buffer = buf
        self._update_main_region_clears()
        if self._debug:
            print(f'[Pax3DRender] aux camera "{reg.name}" attached '
                  f'(sort={reg.sort})')

    def _update_main_region_clears(self):
        """With a background camera present, the main region must preserve
        the background's color output but still clear depth."""
        main_dr = self._find_main_display_region()
        if main_dr is None:
            return
        has_background = any(r.sort < 0 for r in self._scene_cameras)
        if has_background:
            main_dr.set_clear_color_active(False)
            main_dr.set_clear_depth_active(True)

    def _reattach_scene_cameras(self):
        """Called after every _setup_tonemapping(): old buffer (and its
        display regions) are gone; re-create them on the new buffer."""
        for reg in self._scene_cameras:
            reg.display_region = None
            reg.buffer = None
            self._attach_scene_camera(reg)

    # ------------------------------------------------------------------
    # Coordinate system conversion
    # ------------------------------------------------------------------

    def _init_cs_conversion(self):
        """Determine if custom shader inputs need coordinate system conversion.

        Panda3D internally uses Z-up right-handed coordinates. The GSG
        (OpenGL) uses Y-up right-handed. Built-in shader matrices like
        p3d_ModelMatrix include this CS conversion, so normals/positions
        in the shader are in GL Y-up space. Custom shader inputs (via
        set_shader_input) are passed RAW in P3D Z-up space.
        """
        self._cs_mat4 = None  # None = no conversion needed
        self._cs_diag_done = False

        try:
            gsg = self.window.get_gsg() if self.window else None
            if not gsg:
                return

            default_cs = p3d.get_default_coordinate_system()
            gsg_cs = gsg.get_coordinate_system()

            if default_cs != gsg_cs:
                self._cs_mat4 = p3d.LMatrix4f.convert_mat(default_cs, gsg_cs)
                if self._debug:
                    print('[Pax3DRender] CS conversion ACTIVE '
                          '(P3D -> shader world space)')
        except Exception as exc:
            print(f'[Pax3DRender] CS detection failed ({exc}) — '
                  f'no conversion applied')

    def _convert_dir(self, v):
        """Convert a Panda3D direction Vec3 to shader world space."""
        if self._cs_mat4 is None:
            return v
        m = self._cs_mat4
        x = v.x * m.get_cell(0, 0) + v.y * m.get_cell(1, 0) + v.z * m.get_cell(2, 0)
        y = v.x * m.get_cell(0, 1) + v.y * m.get_cell(1, 1) + v.z * m.get_cell(2, 1)
        z = v.x * m.get_cell(0, 2) + v.y * m.get_cell(1, 2) + v.z * m.get_cell(2, 2)
        return p3d.Vec3(x, y, z)

    def _convert_point(self, v):
        return self._convert_dir(v)

    # ------------------------------------------------------------------
    # Post-processing chain
    # ------------------------------------------------------------------

    def _setup_tonemapping(self):
        """Set up tonemapping and optional bloom chain.

        Pipeline:
        1. Scene renders to RGBA16F buffer (HDR)
        2. If bloom enabled: extract -> N downsample -> N upsample passes
        3. Tonemap pass composites bloom (if any) and maps HDR -> sRGB
        """
        # Reset bloom state
        self._bloom_extract_quad = None
        self._bloom_down_quads = []
        self._bloom_up_quads = []

        # Tear down the visibility-query pass (ours, not FilterManager's
        # — its buffer must be removed explicitly on every rebuild)
        if self._vis_buffer is not None:
            self._vis_buffer.get_engine().remove_window(self._vis_buffer)
            self._vis_buffer = None
            self._vis_tex = None
            self._vis_root = None
            self._vis_quad = None

        # 1. Scene -> RGBA16F buffer
        fbprops = p3d.FrameBufferProperties()
        fbprops.float_color = True
        fbprops.srgb_color = False
        fbprops.set_rgba_bits(16, 16, 16, 16)
        fbprops.set_depth_bits(24)
        fbprops.set_multisamples(self.msaa_samples)

        scene_tex = p3d.Texture('scene_hdr')
        scene_tex.set_format(p3d.Texture.F_rgba16)
        scene_tex.set_component_type(p3d.Texture.T_float)
        # Clamp + bilinear: the radial-blur taps in tonemap.frag sample
        # off the pixel grid near the screen edge — Panda's default
        # repeat wrap would bleed the opposite edge in
        scene_tex.set_wrap_u(p3d.SamplerState.WM_clamp)
        scene_tex.set_wrap_v(p3d.SamplerState.WM_clamp)
        scene_tex.set_minfilter(p3d.SamplerState.FT_linear)
        scene_tex.set_magfilter(p3d.SamplerState.FT_linear)

        depth_tex = None
        if self.enable_ssao or self.enable_visibility_query:
            # SSAO / visibility queries need the scene depth. Requested
            # only when a consumer is on, so the default chain is
            # structurally untouched.
            depth_tex = p3d.Texture('scene_depth')
            depth_tex.set_wrap_u(p3d.SamplerState.WM_clamp)
            depth_tex.set_wrap_v(p3d.SamplerState.WM_clamp)
            depth_tex.set_minfilter(p3d.SamplerState.FT_nearest)
            depth_tex.set_magfilter(p3d.SamplerState.FT_nearest)
            postquad = self._filtermgr.render_scene_into(
                colortex=scene_tex, depthtex=depth_tex, fbprops=fbprops
            )
        else:
            postquad = self._filtermgr.render_scene_into(
                colortex=scene_tex, fbprops=fbprops
            )
        self._scene_depth_tex = depth_tex

        if postquad is None:
            raise RuntimeError('[Pax3DRender] Failed to setup FilterManager')

        flare_active = self.enable_lens_flare and self.enable_bloom
        if self.enable_lens_flare and not self.enable_bloom \
                and not self._flare_warned:
            print('[Pax3DRender] enable_lens_flare needs enable_bloom '
                  '(ghosts source from the bright extract) — flare inert')
            self._flare_warned = True

        defines = {
            'ENABLE_BLOOM': self.enable_bloom,
            'ENABLE_SSAO': self.enable_ssao,
            'ENABLE_LENS_FLARE': flare_active,
        }

        ao_result_tex = None
        self._ssao_quad = None
        self._ssao_blur_quad = None
        if self.enable_ssao:
            win_x = self.window.get_x_size()
            win_y = self.window.get_y_size()
            ssao_defines = {
                'LOG_DEPTH': self.enable_log_depth,
                'AO_SAMPLES': self.ao_samples,
            }
            texel = p3d.LVecBase2(1.0 / max(1, win_x), 1.0 / max(1, win_y))
            # AO is a [0,1] scalar — the default 8-bit FBO is a DELIBERATE
            # choice here (256 obscurance levels is standard), unlike the
            # bloom chain where HDR data demands float fbprops (fact #3).
            ao_raw_tex = p3d.Texture('ssao_raw')
            ao_raw_tex.set_wrap_u(p3d.SamplerState.WM_clamp)
            ao_raw_tex.set_wrap_v(p3d.SamplerState.WM_clamp)
            ssao_quad = self._filtermgr.render_quad_into(
                colortex=ao_raw_tex)
            ssao_quad.set_shader(shaderutils.make_shader(
                'ssao', 'post.vert', 'ssao.frag', ssao_defines))
            ssao_quad.set_shader_input('depth_tex', depth_tex)
            ssao_quad.set_shader_input('u_texel', texel)
            ssao_quad.set_shader_input('u_ao_radius', self.ao_radius)
            ssao_quad.set_shader_input('u_ao_intensity', self.ao_intensity)
            ssao_quad.set_shader_input('u_ao_bias', self.ao_bias)
            # Lens params (u_proj_tan/u_near_far/u_log_depth_coef) are
            # pushed every frame by _update — the game changes them.
            self._push_ssao_lens_inputs(ssao_quad)
            self._ssao_quad = ssao_quad

            ao_tex = p3d.Texture('ssao_blurred')
            ao_tex.set_wrap_u(p3d.SamplerState.WM_clamp)
            ao_tex.set_wrap_v(p3d.SamplerState.WM_clamp)
            blur_quad = self._filtermgr.render_quad_into(colortex=ao_tex)
            blur_quad.set_shader(shaderutils.make_shader(
                'ssao_blur', 'post.vert', 'ssao_blur.frag', {
                }))
            blur_quad.set_shader_input('ao_tex', ao_raw_tex)
            blur_quad.set_shader_input('u_texel', texel)
            self._ssao_blur_quad = blur_quad
            ao_result_tex = ao_tex

        bloom_result_tex = None
        flare_result_tex = None
        self._flare_quad = None

        if self.enable_bloom:
            win_x = self.window.get_x_size()
            win_y = self.window.get_y_size()
            num_levels = self.bloom_levels

            bloom_defines = {
            }

            # Bloom buffers must be REAL float FBOs. Without explicit
            # fbprops, render_quad_into creates a default 8-bit framebuffer
            # and the texture bind silently rewrites the declared RGBA16F
            # format to match it — the extract's 0.005 scale then collapses
            # the halo tail into a handful of 8-bit codes, which the tonemap
            # amplifies into visible banding (defect F3).
            bloom_fbprops = p3d.FrameBufferProperties()
            bloom_fbprops.float_color = True
            bloom_fbprops.set_rgba_bits(16, 16, 16, 16)

            # 2. Bloom extract pass (full resolution)
            bloom_extract_tex = p3d.Texture('bloom_extract')
            bloom_extract_tex.set_format(p3d.Texture.F_rgba16)
            bloom_extract_tex.set_component_type(p3d.Texture.T_float)
            _set_bloom_filtering(bloom_extract_tex)
            extract_quad = self._filtermgr.render_quad_into(
                colortex=bloom_extract_tex, fbprops=bloom_fbprops)
            extract_quad.set_shader(shaderutils.make_shader(
                'bloom_extract', 'post.vert', 'bloom_extract.frag',
                bloom_defines
            ))
            extract_quad.set_shader_input('scene_tex', scene_tex)
            extract_quad.set_shader_input('bloom_strength',
                                          self.bloom_strength)
            self._bloom_extract_quad = extract_quad

            # 3. Downsample chain (num_levels levels, each half the previous)
            down_textures = [bloom_extract_tex]
            for i in range(num_levels):
                div = 2 ** (i + 1)
                tex = p3d.Texture(f'bloom_down_{i}')
                tex.set_format(p3d.Texture.F_rgba16)
                tex.set_component_type(p3d.Texture.T_float)
                _set_bloom_filtering(tex)
                quad = self._filtermgr.render_quad_into(
                    colortex=tex, div=div, fbprops=bloom_fbprops)
                quad.set_shader(shaderutils.make_shader(
                    'bloom_down', 'post.vert', 'bloom_downsample.frag',
                    bloom_defines
                ))
                quad.set_shader_input('src_tex', down_textures[-1])
                # Texel size of the SOURCE texture we're reading from
                src_w = max(1, win_x // (2 ** i))
                src_h = max(1, win_y // (2 ** i))
                quad.set_shader_input('texel_size', p3d.LVecBase2(
                    1.0 / src_w, 1.0 / src_h
                ))
                down_textures.append(tex)
                self._bloom_down_quads.append(quad)

            # 4. Upsample chain (from smallest back to full resolution)
            up_tex = down_textures[-1]  # start from smallest mip
            for i in range(num_levels):
                src_idx = len(down_textures) - 2 - i
                remaining = num_levels - 1 - i
                div = 2 ** remaining if remaining > 0 else 1

                tex = p3d.Texture(f'bloom_up_{i}')
                tex.set_format(p3d.Texture.F_rgba16)
                tex.set_component_type(p3d.Texture.T_float)
                _set_bloom_filtering(tex)
                if div > 1:
                    quad = self._filtermgr.render_quad_into(
                        colortex=tex, div=div, fbprops=bloom_fbprops)
                else:
                    quad = self._filtermgr.render_quad_into(
                        colortex=tex, fbprops=bloom_fbprops)
                quad.set_shader(shaderutils.make_shader(
                    'bloom_up', 'post.vert', 'bloom_upsample.frag',
                    bloom_defines
                ))
                quad.set_shader_input('src_tex', down_textures[src_idx])
                quad.set_shader_input('bloom_accum_tex', up_tex)
                # Texel size of the COARSER accumulator — that's what the
                # tent filter reads (matches FilterManager's win//div sizing)
                accum_w = max(1, win_x // (2 ** (src_idx + 1)))
                accum_h = max(1, win_y // (2 ** (src_idx + 1)))
                quad.set_shader_input('texel_size', p3d.LVecBase2(
                    1.0 / accum_w, 1.0 / accum_h
                ))
                # Per-mip tint (cycle if more levels than tints)
                tint = _MIP_TINTS[i % len(_MIP_TINTS)]
                quad.set_shader_input('mip_tint', tint)
                up_tex = tex
                self._bloom_up_quads.append(quad)

            bloom_result_tex = up_tex

            # 4b. Lens flare (Session S): ghosts from a blurred down
            # level of the bright extract. Float fbprops — this carries
            # HDR data (fact #3 discipline), unlike the 8-bit AO pass.
            if flare_active:
                src_idx = min(2, len(down_textures) - 1)
                flare_tex_t = p3d.Texture('lens_flare')
                flare_tex_t.set_format(p3d.Texture.F_rgba16)
                flare_tex_t.set_component_type(p3d.Texture.T_float)
                _set_bloom_filtering(flare_tex_t)
                flare_quad = self._filtermgr.render_quad_into(
                    colortex=flare_tex_t, div=2, fbprops=bloom_fbprops)
                flare_quad.set_shader(shaderutils.make_shader(
                    'lens_flare', 'post.vert', 'lens_flare.frag',
                    bloom_defines))
                flare_quad.set_shader_input('src_tex',
                                            down_textures[src_idx])
                self._apply_lens_dirt_inputs(flare_quad)
                self._flare_quad = flare_quad
                flare_result_tex = flare_tex_t

        # 5. Final tonemap + composite pass
        tonemap_shader = shaderutils.make_shader(
            'tonemap', 'post.vert', 'tonemap.frag', defines
        )

        # TAA state (reset on every rebuild)
        self._tonemap_quad = None
        self._taa_resolve_quad = None
        # Start at -1: first _update() increments to 0, so the first rendered
        # frame sees u_taa_frame=0 -> blend=1.0 (100% current, no black flash).
        self._taa_frame = -1
        self._taa_jitter_index = 0

        if self.enable_taa:
            # --- TAA pipeline: tonemap -> resolve -> history copy -> display

            # Tonemap to intermediate texture (LDR)
            tonemap_tex = p3d.Texture('tonemap_output')
            tonemap_tex.set_format(p3d.Texture.F_rgba8)
            tonemap_quad = self._filtermgr.render_quad_into(
                colortex=tonemap_tex)
            tonemap_quad.set_shader(tonemap_shader)
            tonemap_quad.set_shader_input('tex', scene_tex)
            tonemap_quad.set_shader_input('exposure', 2 ** self.exposure)
            tonemap_quad.set_shader_input(
                'tonemap_operator',
                _TONEMAP_OPERATORS.get(self.tonemap_operator, 0))
            if bloom_result_tex is not None:
                tonemap_quad.set_shader_input('bloom_tex', bloom_result_tex)
                tonemap_quad.set_shader_input('bloom_intensity',
                                              self.bloom_intensity)
            if ao_result_tex is not None:
                tonemap_quad.set_shader_input('ao_tex', ao_result_tex)
            if flare_result_tex is not None:
                tonemap_quad.set_shader_input('flare_tex', flare_result_tex)
                tonemap_quad.set_shader_input('u_flare_strength',
                                              self.flare_strength)
            self._apply_warp_distortion_inputs(tonemap_quad)
            self._tonemap_quad = tonemap_quad

            # Resolved and history textures
            resolved_tex = p3d.Texture('taa_resolved')
            resolved_tex.set_format(p3d.Texture.F_rgba8)
            resolved_tex.set_wrap_u(p3d.SamplerState.WM_clamp)
            resolved_tex.set_wrap_v(p3d.SamplerState.WM_clamp)
            resolved_tex.set_minfilter(p3d.SamplerState.FT_linear)
            resolved_tex.set_magfilter(p3d.SamplerState.FT_linear)

            history_tex = p3d.Texture('taa_history')
            history_tex.set_format(p3d.Texture.F_rgba8)
            history_tex.set_wrap_u(p3d.SamplerState.WM_clamp)
            history_tex.set_wrap_v(p3d.SamplerState.WM_clamp)
            history_tex.set_minfilter(p3d.SamplerState.FT_linear)
            history_tex.set_magfilter(p3d.SamplerState.FT_linear)

            taa_defines = {
            }

            # TAA resolve pass
            winx = self.window.get_x_size()
            winy = self.window.get_y_size()
            taa_resolve_quad = self._filtermgr.render_quad_into(
                colortex=resolved_tex)
            taa_resolve_quad.set_shader(shaderutils.make_shader(
                'taa_resolve', 'post.vert', 'taa_resolve.frag', taa_defines
            ))
            taa_resolve_quad.set_shader_input('current_frame', tonemap_tex)
            taa_resolve_quad.set_shader_input('history', history_tex)
            taa_resolve_quad.set_shader_input(
                'u_resolution', p3d.Vec2(winx, winy))
            taa_resolve_quad.set_shader_input('u_taa_frame', 0.0)
            taa_resolve_quad.set_shader_input('u_debug_taa', 0.0)
            self._taa_resolve_quad = taa_resolve_quad

            # History copy pass (resolved -> history for next frame)
            history_copy_quad = self._filtermgr.render_quad_into(
                colortex=history_tex)
            history_copy_quad.set_shader(shaderutils.make_shader(
                'passthrough_copy', 'post.vert', 'passthrough.frag',
                taa_defines
            ))
            history_copy_quad.set_shader_input('tex', resolved_tex)

            # Final display (postquad -> window)
            display_shader = shaderutils.make_shader(
                'passthrough_display', 'post.vert', 'passthrough.frag',
                taa_defines
            )
            postquad.set_shader(display_shader)
            postquad.set_shader_input('tex', resolved_tex)

        else:
            # Original: tonemap directly on postquad (no TAA overhead)
            postquad.set_shader(tonemap_shader)
            postquad.set_shader_input('tex', scene_tex)
            postquad.set_shader_input('exposure', 2 ** self.exposure)
            postquad.set_shader_input(
                'tonemap_operator',
                _TONEMAP_OPERATORS.get(self.tonemap_operator, 0))
            if bloom_result_tex is not None:
                postquad.set_shader_input('bloom_tex', bloom_result_tex)
                postquad.set_shader_input('bloom_intensity',
                                          self.bloom_intensity)
            if ao_result_tex is not None:
                postquad.set_shader_input('ao_tex', ao_result_tex)
            if flare_result_tex is not None:
                postquad.set_shader_input('flare_tex', flare_result_tex)
                postquad.set_shader_input('u_flare_strength',
                                          self.flare_strength)
            self._apply_warp_distortion_inputs(postquad)

        self._post_process_quad = postquad

        # Visibility-query pass (Session AF) — after the chain exists so
        # its buffer can sort ahead of every FilterManager buffer.
        if self.enable_visibility_query:
            self._build_vis_query_pass(depth_tex)

        # R1: auxiliary cameras survive the rebuild
        self._reattach_scene_cameras()

