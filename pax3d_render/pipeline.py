def _set_bloom_filtering(tex):
    """Bilinear + clamp-to-edge on a bloom intermediate texture.

    The tent/box kernels sample between mismatched resolutions and assume
    this state; Panda's default wrap is repeat, which bleeds the halo
    across screen edges (part of F3).
    """
    tex.set_minfilter(p3d.SamplerState.FT_linear)
    tex.set_magfilter(p3d.SamplerState.FT_linear)
    tex.set_wrap_u(p3d.SamplerState.WM_clamp)
    tex.set_wrap_v(p3d.SamplerState.WM_clamp)


def _load_brdf_lut(debug=False):
    """Load the BRDF LUT texture for IBL specular.

    <package>/textures/brdf_lut.txo is the committed split-sum LUT
    (generated by tools/gen_brdf_lut.py — Session M / R5.3); the 1x1
    white fallback below is only safe while the env map is the 1x1
    black default (ibl_spec = 0 either way). set_env_map() refuses to
    run on the fallback for exactly that reason.
    """
    lut_path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            'textures', 'brdf_lut.txo')
    if os.path.exists(lut_path):
        panda_path = p3d.Filename.from_os_specific(lut_path)
        tex = p3d.TexturePool.load_texture(panda_path)
        if tex:
            tex.wrap_u = p3d.SamplerState.WM_clamp
            tex.wrap_v = p3d.SamplerState.WM_clamp
            tex.minfilter = p3d.SamplerState.FT_linear
            tex.magfilter = p3d.SamplerState.FT_linear
            return tex

    if debug:
        print('[Pax3DRender] No brdf_lut.txo — using white fallback')
    tex = p3d.Texture('brdf_lut_fallback')
    tex.setup_2d_texture(1, 1, p3d.Texture.T_unsigned_byte, p3d.Texture.F_rgb8)
    tex.set_clear_color(p3d.LColor(1, 1, 1, 1))
    tex.wrap_u = p3d.SamplerState.WM_clamp
    tex.wrap_v = p3d.SamplerState.WM_clamp
    return tex


def sh_from_cubemap(tex, band_factors=(math.pi, 2.0 * math.pi / 3.0,
                                       math.pi / 4.0)):
    """Project a cube-map Texture to 9 irradiance-SH coefficients for
    Pipeline.set_ambient_sh() — the R5 "ambient from the skybox" path.

    Face table (PINNED, Session Q 2026-07-18 — do not re-derive): standard
    GL cube-map convention with Panda's Z-up lookup vectors — face 0 = +x
    east, 1 = -x west, 2 = +y north, 3 = -y south, 4 = +z up, 5 = -z down;
    in a file-loaded up-face image the TOP row is the SOUTHERN sky. Proven
    on all three legs: shader sampling (test_env_map mirror proof),
    win.makeCubeMap captures (openworld marker rig, PAX3D_FEEDBACK_2.md
    2026-07-18 — parent the rig to render, not the camera), and
    loader.load_cube_map image files (test_ambient_sh checks 6-8). Runs on
    the CPU from the texture's RAM image (loaded skyboxes have one) — call
    once at scene setup, not per frame; cost scales with face area (a 64px
    cubemap is plenty for irradiance).

    Returns a list of 9 (r, g, b) tuples, or raises RuntimeError if a face
    cannot be read back.
    """
    size = tex.get_x_size()
    if tex.get_texture_type() != p3d.Texture.TT_cube_map or size == 0:
        raise RuntimeError('sh_from_cubemap needs a loaded cube map texture')

    # Shader basis constants, slot order [1, x, z, y, xz, yz, xy,
    # 3z^2-ish, x^2-y^2] (matches pax_pbr.frag irradiance_from_sh).
    def basis(d):
        x, y, z = d
        return (0.282095,
                0.488603 * x, 0.488603 * z, 0.488603 * y,
                1.092548 * x * z, 1.092548 * y * z, 1.092548 * y * x,
                0.946176 * z * z - 0.315392,
                0.546274 * (x * x - y * y))

    # Per-slot cosine-convolution factors (Ramamoorthi): band 0, 1, 2.
    slot_factor = (band_factors[0],) + (band_factors[1],) * 3 \
        + (band_factors[2],) * 5

    coeffs = [[0.0, 0.0, 0.0] for _ in range(9)]
    img = p3d.PNMImage()
    for face in range(6):
        if not tex.store(img, face, 0):
            raise RuntimeError(f'sh_from_cubemap: cannot read face {face}')
        n = img.get_x_size()
        for py in range(n):
            # PNM y runs down from the top; GL face t runs up.
            t = 1.0 - (py + 0.5) / n
            b = 2.0 * t - 1.0
            for px in range(n):
                s = (px + 0.5) / n
                a = 2.0 * s - 1.0
                if face == 0:
                    d = (1.0, -b, -a)      # +x
                elif face == 1:
                    d = (-1.0, -b, a)      # -x
                elif face == 2:
                    d = (a, 1.0, b)        # +y
                elif face == 3:
                    d = (a, -1.0, -b)      # -y
                elif face == 4:
                    d = (a, -b, 1.0)       # +z (up)
                else:
                    d = (-a, -b, -1.0)     # -z (down)
                r2 = a * a + b * b + 1.0
                inv_len = r2 ** -0.5
                dn = (d[0] * inv_len, d[1] * inv_len, d[2] * inv_len)
                # Texel solid angle: dA / r^3, with dA = (2/n)^2 on the
                # unit-distance cube face and r = sqrt(a^2 + b^2 + 1).
                dw = (2.0 / n) ** 2 / (r2 * r2 ** 0.5)
                c = img.get_xel(px, py)
                y_vals = basis(dn)
                for i in range(9):
                    w = y_vals[i] * dw
                    coeffs[i][0] += c[0] * w
                    coeffs[i][1] += c[1] * w
                    coeffs[i][2] += c[2] * w
    return [(coeffs[i][0] * slot_factor[i],
             coeffs[i][1] * slot_factor[i],
             coeffs[i][2] * slot_factor[i]) for i in range(9)]


def data_texture(tex):
    """Stamp the ER-003 data-texture contract onto a Texture (idempotent).

    For heightfields, stamps, masks, and splat/weight maps — any texture
    whose texels are DATA, not color. Works on any Texture regardless of
    origin (loader/VFS/multifile or procedural set_ram_image), from any
    thread, before or after first use:

      1. Compression pinned CM_off. A texture left at CM_default is
         driver-compressed whenever the global `compressed-textures` prc
         is set: F_r16/F_r32 fall to RGTC1/BC4 and F_luminance to DXT1
         (glgsg get_internal_image_format) — the 2025 terracing class.
         CM_off is the only per-texture immunity.
      2. Auto-texture-scale pinned ATS_none (no power-2 resampling under
         any textures-power-2 policy). NOTE: this does NOT guard the
         `texture-scale` prc — that rescale happens inside Texture.read()
         itself, before any stamp can exist. File loads should use
         load_data_texture(), whose PNMImage/PfmFile route never applies
         it (measured; gated by test_data_texture).
      3. sRGB transfer formats unflagged — data is linear by definition.
      4. Single-channel >=16-bit formats normalized to F_r16/F_r32 so the
         GL internal format is the sized single-channel one (1-channel
         images load as F_luminance by default); shader consumers read
         `.r`. Multi-channel textures keep their format: RGBA8 splat
         weights ride clauses 1-3 only, by design.

    Returns the texture (for chaining). Guarded by paxtest
    test_data_texture.
    """
    changed = False
    if tex.get_compression() != p3d.Texture.CM_off:
        tex.set_compression(p3d.Texture.CM_off)
        changed = True
    if tex.get_auto_texture_scale() != p3d.ATS_none:
        tex.set_auto_texture_scale(p3d.ATS_none)
        changed = True
    fmt = tex.get_format()
    new_fmt = None
    if fmt == p3d.Texture.F_srgb:
        new_fmt = p3d.Texture.F_rgb8
    elif fmt == p3d.Texture.F_srgb_alpha:
        new_fmt = p3d.Texture.F_rgba8
    elif tex.get_num_components() == 1:
        ctype = tex.get_component_type()
        if ctype == p3d.Texture.T_unsigned_short:
            new_fmt = p3d.Texture.F_r16
        elif ctype == p3d.Texture.T_float:
            new_fmt = p3d.Texture.F_r32
    if new_fmt is not None and new_fmt != fmt:
        tex.set_format(new_fmt)
        changed = True
    if changed:
        # An already-prepared texture keeps its old internal format until
        # re-uploaded (same trap as set_srgb_inputs) — release so the
        # contract reaches the GPU even when stamping after first use.
        tex.release_all()
    return tex


def load_data_texture(path, name=None):
    """Load a data texture from disk/VFS with the ER-003 contract enforced
    end to end, and return it stamped (see data_texture()).

    Use this instead of Texture.read()/loader.loadTexture() for
    heightfields, stamps, and masks: Texture.read() applies the
    `texture-scale` prc rescale DURING the read (gated only by
    exclude-texture-scale name globs — a stamp afterwards cannot undo
    it), while this route decodes via PNMImage/PfmFile and tex.load(),
    which never rescales (measured; gated by test_data_texture).

    Wire formats: anything PNMImage reads (16-bit PNG/TIFF stay
    T_unsigned_short) plus float EXR/PFM via PfmFile (T_float). R16 RAW
    has no header and is an intake-tool concern, not a loader one.
    Reads through the VFS, so multifile-packed assets work. Raises
    ValueError if the file cannot be read.
    """
    if isinstance(path, p3d.Filename):
        fn = path
    else:
        fn = p3d.Filename.from_os_specific(str(path))
    tex = p3d.Texture(name or fn.get_basename())
    if fn.get_extension().lower() in ('exr', 'pfm'):
        pfm = p3d.PfmFile()
        if not pfm.read(fn):
            raise ValueError(f'load_data_texture: cannot read {fn}')
        tex.load(pfm)
    else:
        img = p3d.PNMImage()
        if not img.read(fn):
            raise ValueError(f'load_data_texture: cannot read {fn}')
        tex.load(img)
    return data_texture(tex)


