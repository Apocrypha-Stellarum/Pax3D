    @staticmethod
    def _halton(index, base):
        """Halton low-discrepancy sequence for sub-pixel jitter."""
        result = 0.0
        f = 1.0
        i = index
        while i > 0:
            f /= base
            result += f * (i % base)
            i //= base
        return result

